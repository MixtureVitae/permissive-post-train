# Rows, resolved against the manifest


@dataclass(frozen=True)
class Row:
    label: str
    base_model: str
    stage: str
    change: bool = True     # print the change against its parent, a row above it


@dataclass
class Resolved:
    row: Row
    key: str
    cells: dict[str, tuple[float, float]]
    avg: tuple[float, float]
    parent: str | None = None
    status: str | None = None
    changes: dict[str, float] | None = None     # per column, as printed; "avg" too


Block = tuple[str | None, list[Row]]


def resolve(m: Manifest, blocks: list[Block]) -> list[tuple[str | None, list[Resolved]]]:
    out = []
    for heading, rows in blocks:
        done: dict[str, Resolved] = {}
        resolved = []
        for row in rows:
            key = m.checkpoint(row.base_model, row.stage)
            suite = m.suite(key)
            cells = {t: (m.result(key, t)["mean"], m.result(key, t)["sd"]) for t in m.tasks()}
            r = Resolved(row, key, cells, (suite["mean"], suite["sd"]))
            if row.change:
                parent, status = m.parent(key)
                if parent not in done:
                    raise ManifestError(
                        f"{row.label} ({key}) was trained from {parent}, which is not a row "
                        f"printed above it.")
                exact = m.change(key)["change"]
                start = done[parent]
                r.parent, r.status = parent, status
                r.changes = {t: printed(cells[t][0] - start.cells[t][0]) for t in cells}
                r.changes["avg"] = printed(r.avg[0] - start.avg[0])
                if abs((r.avg[0] - start.avg[0]) - exact) > 1e-4:
                    raise ManifestError(f"{key}: the suite averages give a change of "
                                        f"{r.avg[0] - start.avg[0]}, the manifest {exact}.")
            done[key] = r
            resolved.append(r)
        out.append((heading, resolved))
    return out


