def _excluded(m: Manifest) -> str:
    """The sentence naming the tasks the manifest leaves out, with a leading space, or ""."""
    excluded = list(m.excluded())
    if not excluded:
        return ""
    one = len(excluded) == 1
    return (f" {' and '.join(excluded)} {'is' if one else 'are'} left out while "
            f"{'it is' if one else 'they are'} re-evaluated.")


def _note(m: Manifest) -> str:
    n = len(m.tasks())
    return (r"Protocol~B (Appendix Table~\ref{tab:eval-settings-B}). Values are "
            r"mean$_{\pm\text{SD}}$ over three sampled runs, and Avg is the mean over the "
            f"{number_word(n)} tasks shown." + _excluded(m))


#: The column panels of the grid of reasoning corpora: the five mathematics tasks,
#: then the other six tasks and the average.
GRID_PANELS = (("Mathematics", 5), ("Code, science and instruction following, and the average", None))


def _blocks_panels(m: Manifest, blocks, caption: str, label: str, first_col: str) -> list[str]:
    """The "heading" style of _blocks_table cut into the column panels of
    GRID_PANELS, stacked in one float at a readable size."""
    tasks = m.tasks()
    cuts = [0] + [n for _, n in GRID_PANELS if n is not None] + [len(tasks)]
    lines = [r"\begin{table}[t]", r"\centering", f"\\caption{{{caption}}}", f"\\label{{{label}}}",
             r"\footnotesize", r"\setlength{\tabcolsep}{3pt}"]
    for k, (title, _) in enumerate(GRID_PANELS):
        mine = tasks[cuts[k]:cuts[k + 1]]
        last = k == len(GRID_PANELS) - 1
        width = len(mine) + 1 + last
        lines += ([r"\par\medskip"] if k else []) + [
            r"\begin{tabular}{l" + "r" * (width - 1) + "}", r"\toprule",
            f"\\multicolumn{{{width}}}{{l}}{{\\textbf{{({'abc'[k]}) {title}}}}} \\\\", r"\midrule",
            f"\\textbf{{{first_col}}} & " + " & ".join(f"\\textbf{{{ABBR[t]}}}" for t in mine)
            + (r" & \textbf{Avg}" if last else "") + r" \\"]
        for heading, rows in blocks:
            lines += [r"\midrule", f"\\multicolumn{{{width}}}{{l}}{{\\emph{{{heading}}}}} \\\\"]
            for r in rows:
                cells = [_ms(*r.cells[t]) for t in mine]
                if last:
                    avg = _ms(*r.avg)
                    if r.changes is not None:
                        avg += f"~{{\\scriptsize(${r.changes['avg']:+.1f}$)}}"
                    cells.append(avg)
                lines.append(r"\quad " + r.row.label + " & " + " & ".join(cells) + r" \\")
        lines += [r"\bottomrule", r"\end{tabular}"]
    lines += [r"\end{table}", ""]
    return lines


