_SUBMITTED_ENDPOINTS = ([(MV, "base"), (MV, "OT3+SFT"), (MV, "OT3+DPO"), (MV, "OT3")]
                        + [(bm, s) for bm in REFERENCES for s in ("SFT-Tulu3", "OT3+SFT")])
_SUBMITTED_ABLATION = [(MV, "base"), (MV, "OT3"), (MV_NO_OT3, "OT3")]
_GRID_START = {"base": "base", "sft": "SFT-Tulu3", "dpo": "DPO-Tulu3"}


def compare_with_submission(m: Manifest, cells: list[HeldoutCell]) -> pd.DataFrame:
    """One row per submitted cell that has a counterpart in the manifest."""
    task_of = {v: k for k, v in ABBR.items()}
    same_tasks = not m.excluded()
    rows = []

    def add(table, label, bm, stage, values):
        key = m.checkpoint(bm, stage)
        for abbr, old in zip(pb.BENCH_ORDER + ("Avg",), values):
            if abbr == "Avg":
                new, like = m.suite(key)["mean"], same_tasks
            else:
                task = task_of[abbr]
                new = m.result(key, task)["mean"] if task in m.tasks() else None
                like = True
            rows.append(dict(table=table, row=label, checkpoint=key, column=abbr,
                             submitted=old, manifest=None if new is None else round(new, 1),
                             like_for_like=like and new is not None))

    for (group, label, _, vals), (bm, stage) in zip(pb.PHASE2_ENDPOINTS, _SUBMITTED_ENDPOINTS):
        add("phase2_endpoints", f"{group} {label}", bm, stage, vals)
    for (label, vals), (bm, stage) in zip(pb.OT3_PRETRAIN_ABLATION, _SUBMITTED_ABLATION):
        add("ot3_pretrain_ablation", label, bm, stage, vals)
    for start, grid in pb.HELDOUT_MV_GRID.items():
        stages = [_GRID_START[start]] + [corpus_stage(p, _GRID_START[start]) for _, p in CORPORA]
        for (label, vals), stage in zip(grid, stages):
            add("heldout_mv_grid", f"from {start}: {label}", MV, stage, vals)
    name_of = {v[0]: k for k, v in MODELS.items()}
    for base, old_cells in pb.HELDOUT_MATH500.items():
        for (corpus, _), (est, _, _, _) in zip(CORPORA, old_cells):
            new = next(c for c in cells if c.base_model == name_of[base] and c.corpus == corpus)
            rows.append(dict(table="heldout_reasoning", row=f"{base} {corpus}", checkpoint=new.key,
                             column="M500 change", submitted=est,
                             manifest=printed(new.change.estimate), like_for_like=True))
    out = pd.DataFrame(rows)
    out["difference"] = (out["manifest"] - out["submitted"]).round(1)
    return out
