SIGNIFICANCE = 0.05


def significant(q: float) -> bool:
    """q < SIGNIFICANCE, where a q that equals it up to rounding (0.049999999999999996
    for 0.0025 x 20) is not below it."""
    return q < SIGNIFICANCE - 1e-9


def corpus_stage(prefix: str, start: str) -> str:
    return {"base": prefix, "SFT-Tulu3": f"{prefix}+SFT", "DPO-Tulu3": f"{prefix}+DPO"}[start]


def stage_id(stage: str) -> str:
    named = {"base": "base", "SFT-Tulu3": "sft", "DPO-Tulu3": "dpo"}
    if stage in named:
        return named[stage]
    if "+" in stage:
        prefix, start = stage.split("+", 1)
        return f"{start.lower()}-{prefix.lower()}"
    return stage.lower()


def printed(x: float) -> float:
    """The value as printed with one decimal (rounded once, no negative zero)."""
    return round(float(f"{x:.1f}"), 1) + 0.0


def _ms(mean: float, sd: float) -> str:
    return f"{mean:.1f}$_{{\\pm{sd:.2f}}}$"


def _write(out_dir: Path, name: str, lines: list[str]) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / name
    path.write_text(HEADER + "\n".join(lines))
    return path


