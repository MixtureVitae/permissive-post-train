# Macros for numbers quoted in the text


def macros(tables: list, cells: list[HeldoutCell]) -> dict[str, str]:
    """Key -> printed text. Keys are <model>.<checkpoint>.<column> for values,
    <model>.<checkpoint>.change.<column> for printed changes,
    <model>.<checkpoint>.change.m500.lo / .hi for MATH500 intervals, and
    noot3-gap.<checkpoint>.<column> for Table 3's MV minus MV without
    OpenThoughts3. Changes and gaps are computed from unrounded values."""
    out: dict[str, str] = {}
    raw: dict[str, float] = {}
    for blocks in tables:
        for _, rows in blocks:
            for r in rows:
                stem = f"{MODELS[r.row.base_model][1]}.{stage_id(r.row.stage)}"
                for t, (mean, _) in r.cells.items():
                    out[f"{stem}.{ABBR[t].lower()}"] = f"{mean:.1f}"
                    raw[f"{stem}.{ABBR[t].lower()}"] = mean
                out[f"{stem}.avg"] = f"{r.avg[0]:.1f}"
                raw[f"{stem}.avg"] = r.avg[0]
                out[f"{stem}.avg.sd"] = f"{r.avg[1]:.2f}"
                for col, v in (r.changes or {}).items():
                    name = col if col == "avg" else ABBR[col].lower()
                    out[f"{stem}.change.{name}"] = f"\\ensuremath{{{v:+.1f}}}"
    for c in cells:
        stem = f"{MODELS[c.base_model][1]}.{stage_id(c.stage)}"
        out[f"{stem}.change.m500"] = f"\\ensuremath{{{printed(c.change.estimate):+.1f}}}"
        out[f"{stem}.change.m500.lo"] = f"\\ensuremath{{{printed(c.change.lo):+.1f}}}"
        out[f"{stem}.change.m500.hi"] = f"\\ensuremath{{{printed(c.change.hi):+.1f}}}"
    for key, v in raw.items():
        stem, _, rest = key.partition(".")
        other = raw.get(f"{MODELS[MV_NO_OT3][1]}.{rest}")
        if stem == "mv" and other is not None:
            d = printed(v - other)
            out[f"noot3-gap.{rest}"] = f"\\ensuremath{{{d:.1f}}}" if d < 0 else f"{d:.1f}"
    return dict(sorted(out.items()))


