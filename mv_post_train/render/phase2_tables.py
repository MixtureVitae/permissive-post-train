#: Table 3's two models, in print order, with their block titles.
ABLATION_TITLES = ((MV, "With OT3 source"), (MV_NO_OT3, "Without OT3 source"))
#: A mean with its SD below it, and a row label set on the mean's line.
ABLATION_COMMANDS = (
    r"\newcommand{\otstat}[2]{\shortstack[c]{#1\\[-0.5pt]{\footnotesize $\pm #2$}}}",
    r"\newcommand{\otstage}[1]{\shortstack[l]{#1\\[-0.5pt]{\footnotesize\strut}}}")


def _ablation_table(m: Manifest, blocks, caption: str, label: str) -> list[str]:
    """Table 3: each model's 16K extended checkpoint ("Before") above its OT30K run
    ("After"), every mean with its SD below it, and the two gains in a note under
    the table. The rows are those of `ot3_ablation_blocks`, whose labels the
    analyses of Appendix E print."""
    tasks = m.tasks()
    width = len(tasks) + 2
    rows = [r for _, rs in blocks for r in rs]
    pairs = []
    for bm, title in ABLATION_TITLES:
        before = next(r for r in rows if r.row.base_model == bm and r.parent is None)
        after = next(r for r in rows if r.row.base_model == bm and r.parent is not None)
        if (before.row.stage, after.row.stage, after.parent) != ("base", "OT3", before.key):
            raise ManifestError(f"Table 3 shows {after.key} as OT30K from {before.key}, "
                                f"but it was trained from {after.parent}.")
        pairs.append((title, before, after))

    spans: list[list] = []          # [group, first task index, last task index]
    for i, t in enumerate(tasks):
        g = ABLATION_GROUPS.get(t)
        if spans and spans[-1][0] == g:
            spans[-1][2] = i
        else:
            spans.append([g, i, i])
    groups = []
    for g, a, b in spans:
        groups += [""] * (b - a + 1) if g is None else [f"\\multicolumn{{{b - a + 1}}}{{c}}{{{g}}}"]
    rules = "".join(f"\\cmidrule(lr){{{a + 2}-{b + 2}}}" for g, a, b in spans if g is not None)

    def stat(mean: float, sd: float) -> str:
        return f"\\otstat{{{mean:.1f}}}{{{sd:.2f}}}"

    def gain(r: Resolved) -> str:
        return f"${r.changes['avg']:+.1f}$"

    lines = [r"\begin{table}[t]", f"\\caption{{{caption}}}", f"\\label{{{label}}}",
             *ABLATION_COMMANDS,
             r"\begingroup", r"\small", r"\setlength{\tabcolsep}{2pt}",
             r"\renewcommand{\arraystretch}{1.05}", r"\centering",
             f"\\begin{{tabular*}}{{\\linewidth}}{{@{{\\extracolsep{{\\fill}}}}l*{{{width - 1}}}{{c}}@{{}}}}",
             r"\toprule",
             "& " + " & ".join(groups + [""]) + r" \\", rules,
             "Stage & " + " & ".join(f"\\textbf{{{ABBR[t]}}}" for t in tasks) + r" & \textbf{Avg} \\",
             r"\midrule"]
    for k, (title, before, after) in enumerate(pairs):
        if k:
            lines.append(r"\addlinespace[1pt]")
        lines.append(f"\\multicolumn{{{width}}}{{@{{}}l}}{{\\textit{{{title}}}}} \\\\[2pt]")
        for name, r in (("Before", before), ("After", after)):
            cells = [stat(*r.cells[t]) for t in tasks] + [stat(*r.avg)]
            lines.append(f"\\otstage{{{name}}} & " + " & ".join(cells) + r" \\[3pt]")
    (_, _, with_), (_, _, without) = pairs
    note = (r"\textbf{Suite-average gain:} with the OT3 source, " + gain(with_)
            + ", without it, " + gain(without) + " points.")
    lines += [r"\bottomrule", r"\end{tabular*}", r"\par", r"\endgroup", "", r"\vspace{3pt}",
              r"\noindent\begin{minipage}{\linewidth}\footnotesize",
              note, r"\end{minipage}", r"\end{table}", ""]
    return lines


