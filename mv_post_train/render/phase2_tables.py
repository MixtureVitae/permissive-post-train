"""The paper's Phase 2 tables, rendered from the results manifest.

Four tables replace the hand-copied Protocol B ones (Tables 2, 3, 4 and 32 of
the revision). The settings table for the protocol and a file of LaTeX macros
for the numbers quoted in the text come with them. Unlike
`workshop_tables.py`, nothing here is transcribed:

  - every cell is a manifest result: mean and SD over the three runs;
  - every Avg is a manifest suite average;
  - every printed change is against the checkpoint's recorded parent, which
    must be a row printed above it in the same block, and must be a change
    the manifest computed (`manifest/reader.py`);
  - MATH500 intervals come from the per-question records, which must
    reproduce the manifest's per-run scores.

The columns are the manifest's Phase 2 tasks. A task the manifest leaves out
has no column, and the captions say so. None is left out since the GSM8K
re-run of 2026-10-15.

Every value is rounded once, when it is printed. A change is computed from the
unrounded values and then rounded, so it can differ in the last digit from the
difference of the two printed values.
"""
