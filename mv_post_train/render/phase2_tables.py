@dataclass(frozen=True)
class HeldoutCell:
    base_model: str
    corpus: str
    stage: str
    key: str
    status: str
    change: PairedChange

    @property
    def sign(self) -> str:
        if not significant(self.change.q):
            return ""
        return "+" if self.change.estimate > 0 else "-"


def _records_match(m: Manifest, meta: pd.DataFrame, key: str, task: str) -> dict:
    src = m.result(key, task)["source"]
    ours = run_scores(meta, src["base_model"], src["stage"], src["task"])
    theirs = sorted(m.result(key, task)["per_seed"].values())
    if len(ours) != len(theirs) or any(abs(a - b) > 1e-3 for a, b in zip(ours, theirs)):
        raise ManifestError(f"{key} {task}: the per-question records give runs {ours}, the "
                            f"manifest {theirs}.")
    return src


def heldout_changes(m: Manifest, meta: pd.DataFrame, task: str = HELDOUT_TASK
                    ) -> list[HeldoutCell]:
    pairs, info = [], []
    for bm in HELDOUT_BASES:
        start = m.checkpoint(bm, "SFT-Tulu3")
        start_src = _records_match(m, meta, start, task)
        for corpus, prefix in CORPORA:
            stage = corpus_stage(prefix, "SFT-Tulu3")
            key = m.checkpoint(bm, stage)
            delta, parent, status = m.task_change(key, task)
            if parent != start:
                raise ManifestError(f"{key} was trained from {parent}, not from the Tulu3 SFT "
                                    f"checkpoint {start}.")
            src = _records_match(m, meta, key, task)
            pairs.append((item_scores(meta, src["base_model"], src["stage"], src["task"]),
                          item_scores(meta, start_src["base_model"], start_src["stage"],
                                      start_src["task"])))
            info.append((bm, corpus, stage, key, status, delta))
    cells = []
    for (bm, corpus, stage, key, status, delta), ch in zip(info, paired_changes(pairs)):
        if abs(ch.estimate - delta) > 1e-3:
            raise ManifestError(f"{key} {task}: the records give a change of {ch.estimate}, "
                                f"the manifest {delta}.")
        cells.append(HeldoutCell(bm, corpus, stage, key, status, ch))
    return cells


