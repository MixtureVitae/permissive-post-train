def change_intervals_table(runs: list[Run], main: dict, runs12: dict, out_dir: Path) -> Path:
    caption = (r"\textbf{Phase 2 changes on the suite average, with intervals.} The change of "
               r"every run between the checkpoints of Table~\ref{tab:phase2_endpoints_full}, each "
               r"against the checkpoint it was trained from: the updates of "
               r"Table~\ref{tab:phase2_endpoints} and MixtureVitae's two Tulu3 steps. "
               + INTERVAL_NOTE + " " + CODE_NOTE + " " + MARK_NOTE +
               f" over the {len(runs)} changes. " + RUNS12_NOTE)
    body, last = [], None
    for r in runs:
        if r.block != last:
            if last is not None:
                body.append(r"\midrule")
            body.append(f"\\multicolumn{{4}}{{l}}{{\\emph{{{r.block}}}}} \\\\")
            last = r.block
        a, b = main[r.stem], runs12[r.stem]
        body.append(f"\\quad {r.update} & {_cell(a)} & {_q(a.q)} & "
                    f"{_cell(b, marked=False)} \\\\")
    head = (r"\textbf{Run} & \textbf{Change, 95\% interval} & \textbf{$q$} & "
            r"\textbf{Runs 1 and 2 only} \\")
    return _write(out_dir, "phase2_change_intervals.tex",
                  _table(caption, "tab:phase2_change_intervals", "lrrr", head, body, fit=False))


def endpoints_table(m: Manifest, main: dict, out_dir: Path) -> Path:
    """Table 2: each OT30K update's endpoint on every task and on the suite
    average, and the change in the suite average with its interval, as in
    `change_intervals_table`. The appendix version (`pt.phase2_endpoints_full`)
    gives the starting checkpoints and every SD."""
    tasks = m.tasks()
    ups = pt.updates(pt.resolve(m, pt.endpoint_blocks()))
    groups = list(dict.fromkeys(u.group for u in ups))
    width = len(tasks) + 3
    caption = (
        r"\textbf{Reasoning post-training.} Every row receives the same OpenThoughts3-30K "
        r"update. Benchmark columns and the suite average are the endpoint, and $\Delta$ is the "
        r"change in the suite average from each row's starting checkpoint. Evaluation uses "
        r"Protocol~B rather than Table~\ref{tab:phase1_zoo}'s Protocol~A. "
        r"Scores are on the full benchmarks, which include items identified in the training data "
        r"(Section~\ref{sec:methods-decontam}), so they are not uniformly held-out estimates. "
        r"Starting scores and SDs are in Appendix Table~\ref{tab:phase2_endpoints_full}, and the "
        r"interval method in Appendix~\ref{app:stats}." + pt._excluded(m))

    def delta(u: pt.Update) -> str:
        iv = main[f"{pt.MODELS[u.after.row.base_model][1]}.{pt.stage_id(u.after.row.stage)}"]
        return (f"${_num(iv.estimate)}$~"
                f"{{\\footnotesize$[{_num(iv.lo)}, {_num(iv.hi)}]$}}")

    lines = [r"\begin{table}[t]", f"\\caption{{{caption}}}", r"\label{tab:phase2_endpoints}",
             r"\centering", r"\small", r"\setlength{\tabcolsep}{0.5pt}",
             f"\\begin{{tabular*}}{{\\linewidth}}{{@{{\\extracolsep{{\\fill}}}}l*{{{width - 1}}}{{c}}@{{}}}}",
             r"\toprule",
             f"& \\multicolumn{{{len(tasks)}}}{{c}}{{\\textbf{{Benchmark means after OT3-30K}}}} "
             r"& \multicolumn{2}{c}{\textbf{Suite average}} \\",
             f"\\cmidrule(lr){{2-{len(tasks) + 1}}}\\cmidrule(l){{{width - 1}-{width}}}",
             "Model & " + " & ".join(f"{{\\footnotesize {pt.ABBR[t]}}}" for t in tasks)
             + r" & {\footnotesize Avg} & {\footnotesize $\Delta$ [95\% CI]} \\",
             r"\midrule"]
    group = subgroup = None
    for u in ups:
        if u.group != group:
            if group is not None:
                lines.append(r"\midrule")
            letter = "abcdefgh"[groups.index(u.group)]
            lines.append(f"\\multicolumn{{{width}}}{{@{{}}l}}{{\\textbf{{({letter}) {u.group}}}}} \\\\")
            group, subgroup = u.group, None
        if u.subgroup and u.subgroup != subgroup:
            if subgroup is not None:
                lines.append(r"\addlinespace")
            lines.append(f"\\multicolumn{{{width}}}{{@{{}}l}}{{\\textit{{{u.subgroup}}}}} \\\\")
            subgroup = u.subgroup
        cells = [f"{u.after.cells[t][0]:.1f}" for t in tasks] + [f"{u.after.avg[0]:.1f}", delta(u)]
        lines.append(f"{u.label} & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular*}", r"\end{table}", ""]
    return _write(out_dir, "phase2_endpoints.tex", lines)


