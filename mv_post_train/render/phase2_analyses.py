@dataclass(frozen=True)
class Run:
    """One trained checkpoint and the one it was trained from."""
    block: str
    start: str          # the parent, in words
    update: str         # what the run trained on, in words
    base_model: str
    stage: str
    key: str
    parent: str
    status: str

    @property
    def stem(self) -> str:
        return f"{pt.MODELS[self.base_model][1]}.{pt.stage_id(self.stage)}"


def _run(m: Manifest, block: str, start: str, update: str, bm: str, stage: str) -> Run:
    key = m.checkpoint(bm, stage)
    _, parent, status = m.task_change(key, "MATH500")   # refuses a rejected or unusable parent
    return Run(block, start, update, bm, stage, key, parent, status)


def _has(m: Manifest, run: Run, tasks) -> bool:
    """Whether the run and its parent both have a result for every task."""
    try:
        for t in tasks:
            m.result(run.key, t), m.result(run.parent, t)
    except ManifestError:
        return False
    return True


def table2_runs(m: Manifest) -> list[Run]:
    """The changes Table 2 prints, in its order, with Table 2's row labels."""
    out = []
    for heading, rows in pt.resolve(m, pt.endpoint_blocks()):
        for r in rows:
            if r.parent:
                out.append(Run(heading, "", r.row.label, r.row.base_model, r.row.stage, r.key,
                               r.parent, r.status))
    return out


def exclusion_runs(m: Manifest) -> tuple[Run, Run]:
    """Table 3's two OT30K runs: with OT3 in pretraining, and without."""
    rows = [r for _, rs in pt.resolve(m, pt.ot3_ablation_blocks()) for r in rs if r.parent]
    with_, without = (next(r for r in rows if r.row.base_model == bm)
                      for bm in (pt.MV, pt.MV_NO_OT3))
    return tuple(Run("", "", r.row.label, r.row.base_model, r.row.stage, r.key, r.parent, r.status)
                 for r in (with_, without))


def all_runs(m: Manifest) -> list[Run]:
    """Every run of Tables 2, 3, 4 and 32, grouped by base model."""
    title = pt.ENDPOINT_TITLE
    out = []
    for start in ("base", "SFT-Tulu3", "DPO-Tulu3"):
        if start in PHASE1:
            prev, name = PHASE1[start]
            out.append(_run(m, title[pt.MV], START_NAME[prev], name, pt.MV, start))
        for corpus, prefix in CORPORA:
            out.append(_run(m, title[pt.MV], START_NAME[start], corpus, pt.MV,
                            pt.corpus_stage(prefix, start)))
    out.append(_run(m, pt.MODELS[pt.MV_NO_OT3][0] + "-16K", START_NAME["base"], "OpenThoughts3",
                    pt.MV_NO_OT3, "OT3"))
    for bm in pt.REFERENCES:
        corpora = CORPORA if bm in pt.HELDOUT_BASES else CORPORA[:1]   # Table 4, or Table 2
        for corpus, prefix in corpora:
            out.append(_run(m, title[bm], START_NAME["SFT-Tulu3"], corpus, bm,
                            pt.corpus_stage(prefix, "SFT-Tulu3")))
    return out


