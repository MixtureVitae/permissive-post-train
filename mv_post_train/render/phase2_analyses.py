def _domain_panel(r: Run) -> str:
    corpus = r.update in dict(CORPORA)
    if corpus and r.start == START_NAME["SFT-Tulu3"] and r.base_model != pt.MV_NO_OT3:
        return "a"
    if corpus and r.base_model == pt.MV:
        return "b"
    return "c"


def _cell_stacked(iv: ps.Interval, marked: bool = True) -> str:
    """_cell with the interval below the estimate, to keep the columns narrow."""
    est = _num(iv.estimate)
    if marked and iv.q < SIGNIFICANCE:
        est = (r"\bm{" if iv.estimate > 0 else r"\mathit{") + est + "}"
    return f"\\makecell[r]{{${est}$\\\\{{\\scriptsize$[{_num(iv.lo)}, {_num(iv.hi)}]$}}}}"


def domain_table(m: Manifest, runs: list[Run], ivs: dict, out_dir: Path) -> Path:
    domains = ps.domain_tasks(m)
    names = {"math": "Math", "code": "Code", "sci": "Sci.\\ and QA", "if": "IFEval",
             "nonmath": "All but math"}
    caption = (r"\textbf{Phase 2 changes by domain.} Every run of Tables~\ref{tab:phase2_endpoints_full}, "
               r"\ref{tab:ot3_pretrain_ablation}, \ref{tab:heldout_reasoning} and "
               r"\ref{tab:heldout_mv_grid}, against the checkpoint it was trained from, on the "
               r"mean of each domain's tasks (Table~\ref{tab:eval-settings-A} gives each task's "
               r"domain) and of every task but mathematics, in three panels. Brackets are 95\% "
               r"intervals (Appendix~\ref{app:stats}). " + MARK_NOTE + r" within each column, over "
               r"all three panels. A dash marks a domain with a task that the run or its parent was "
               r"not evaluated on.")
    head = (r"\textbf{From} & \textbf{Update} & " + " & ".join(f"\\textbf{{{names[d]}}}"
                                                           for d in domains) + r" \\")
    width = len(domains) + 2
    lines = []
    for f, panels in enumerate((DOMAIN_PANELS[:1], DOMAIN_PANELS[1:])):
        lines += [r"\begin{table}[t]", *([r"\ContinuedFloat"] if f else []), r"\centering",
                  f"\\caption{{{caption if f == 0 else '(continued) Panels (b) and (c).'}}}",
                  *([r"\label{tab:phase2_domain_changes}"] if f == 0 else []),
                  r"\scriptsize", r"\setlength{\tabcolsep}{2pt}", r"\renewcommand{\arraystretch}{0.8}"]
        for i, (key, title) in enumerate(panels):
            body, last = [], None
            for r in runs:
                if _domain_panel(r) != key:
                    continue
                if r.block != last:
                    if last is not None:
                        body.append(r"\midrule")
                    body.append(f"\\multicolumn{{{width}}}{{l}}{{\\emph{{{r.block}}}}} \\\\")
                    last = r.block
                cells = [_cell_stacked(ivs[(d, r.stem)]) if (d, r.stem) in ivs else "--"
                         for d in domains]
                body.append(f"\\quad {r.start} & {r.update} & " + " & ".join(cells) + r" \\")
            lines += ([r"\par\medskip"] if i else []) + [
                r"\begin{tabular}{ll" + "r" * len(domains) + "}", r"\toprule",
                f"\\multicolumn{{{width}}}{{l}}{{\\textbf{{({key}) {title}}}}} \\\\", r"\midrule",
                head, r"\midrule", *body, r"\bottomrule", r"\end{tabular}"]
        lines += [r"\end{table}", ""]
    return _write(out_dir, "phase2_domain_changes.tex", lines)


def _ending_rows(m: Manifest) -> list[tuple[str, str, str, str]]:
    """(block, row label, base_model, stage) for Tables 2 and 3's checkpoints."""
    rows = []
    for heading, rs in pt.resolve(m, pt.endpoint_blocks()):
        rows += [(heading, r.row.label, r.row.base_model, r.row.stage) for r in rs]
    for _, rs in pt.resolve(m, pt.ot3_ablation_blocks()):
        rows += [(pt.MODELS[pt.MV_NO_OT3][0] + "-16K", r.row.label, r.row.base_model, r.row.stage)
                 for r in rs if r.row.base_model == pt.MV_NO_OT3]
    return rows


def _record_task(m: Manifest, key: str, task: str) -> str:
    return m.result(key, task)["source"]["task"]


def endings_table(m: Manifest, shares: pd.DataFrame, column: str, out_dir: Path) -> Path:
    by = shares.set_index(["base_model", "stage", "task"])
    answer = {pt.ABBR[t] for t in m.tasks()
              if _record_task(m, m.checkpoint(pt.MV, "SFT-Tulu3"), t) in ae.ANSWER_TASKS}
    tasks = [t for t in m.tasks()
             if column == "cut_off" or t in ps.CODE_TASKS or pt.ABBR[t] in answer]
    rows = _ending_rows(m)
    if column == "cut_off":
        name, label = "phase2_cutoff.tex", "tab:phase2_cutoff"
        caption = (r"\textbf{Answers near the token limit.} Share of the answers, in percent "
                   r"over the three runs, whose length, counted with each checkpoint's own "
                   f"tokenizer, is at least {ae.LIMIT_SHARE * 100:.0f}\\% of the generation limit of "
                   r"Table~\ref{tab:eval-settings-B}, since re-encoding a sampled answer can give a "
                   r"few percent fewer tokens than were generated. This is a length criterion, "
                   r"not the reason a generation stopped. The rows "
                   r"are those of Tables~\ref{tab:phase2_endpoints_full} and~\ref{tab:ot3_pretrain_ablation}.")
    else:
        name, label = "phase2_no_answer.tex", "tab:phase2_no_answer"
        caption = (r"\textbf{Answers with no final answer, and code answers with no code "
                   r"block.} Share of the answers, in percent over the three runs. For the "
                   r"mathematics and science tasks, the share from which the grader extracts no "
                   r"final answer to compare with the reference, so that the answer is scored "
                   r"wrong. For the code tasks, the share with no code block. The checker then "
                   r"runs the whole answer, so such an answer is not scored wrong for that "
                   r"reason alone. GSM8K and GPQA-Diamond are left out, because "
                   r"their graders take an answer from every response, and IFEval has no answer "
                   r"to extract. A dash marks a cell in which the records do not hold the "
                   r"extracted answer or code. The rows are "
                   r"those of Tables~\ref{tab:phase2_endpoints_full} and~\ref{tab:ot3_pretrain_ablation}.")
    body, last = [], None
    for block, text, bm, stage in rows:
        if block != last:
            if last is not None:
                body.append(r"\midrule")
            body.append(f"\\multicolumn{{{len(tasks) + 1}}}{{l}}{{\\emph{{{block}}}}} \\\\")
            last = block
        key = m.checkpoint(bm, stage)
        cells = []
        for t in tasks:
            col = column if column == "cut_off" or t not in ps.CODE_TASKS else "no_code"
            v = by.loc[(bm, stage, _record_task(m, key, t)), col]
            cells.append("--" if pd.isna(v) else f"{v:.1f}")
        body.append(f"\\quad {text} & " + " & ".join(cells) + r" \\")
    head = r"\textbf{Model} & " + " & ".join(f"\\textbf{{{pt.ABBR[t]}}}" for t in tasks) + r" \\"
    size = r"\scriptsize" if len(tasks) > 9 else r"\footnotesize"   # the cut-off table is wider
    return _write(out_dir, name, _table(caption, label, "l" + "r" * len(tasks), head, body,
                                        size=size, sep="2pt"))


