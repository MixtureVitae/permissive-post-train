# Contrasts


def _tasks(m: Manifest, measure: str) -> tuple[str, ...]:
    if measure == "avg":
        return tuple(m.tasks())
    if measure == "m500":
        return ("MATH500",)
    return ps.domain_tasks(m)[measure]


def table2_contrasts(m: Manifest, runs: list[Run], family: str) -> list[ps.Contrast]:
    return [ps.change(family, r.stem, r.key, r.parent, _tasks(m, "avg")) for r in runs]


def exclusion_contrasts(m: Manifest, with_: Run, without: Run, family: str) -> list[ps.Contrast]:
    out = []
    for measure in MEASURES:
        tasks = _tasks(m, measure)
        out += [ps.change(family, f"with-ot3.{measure}", with_.key, with_.parent, tasks),
                ps.change(family, f"without-ot3.{measure}", without.key, without.parent, tasks),
                ps.gain_difference(family, f"difference.{measure}", (with_.key, with_.parent),
                                   (without.key, without.parent), tasks)]
    return out


def domain_contrasts(m: Manifest, runs: list[Run]) -> list[ps.Contrast]:
    """Each run's change in each domain whose tasks it and its parent both have."""
    domains = ps.domain_tasks(m)
    return [ps.change(f"domain.{d}", r.stem, r.key, r.parent, tasks)
            for d, tasks in domains.items() for r in runs if _has(m, r, tasks)]


