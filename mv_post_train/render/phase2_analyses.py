# LaTeX


def _num(x: float) -> str:
    return f"{pt.printed(x):+.1f}"


def _ci(iv: ps.Interval) -> str:
    return f"[{_num(iv.lo)}, {_num(iv.hi)}]"


def _cell(iv: ps.Interval, marked: bool = True) -> str:
    est = _num(iv.estimate)
    if marked and iv.q < SIGNIFICANCE:
        est = (r"\bm{" if iv.estimate > 0 else r"\mathit{") + est + "}"
    return f"${est}$ {{\\scriptsize$[{_num(iv.lo)}, {_num(iv.hi)}]$}}"


def _q(q: float) -> str:
    return "$<0.001$" if q < 0.001 else f"${q:.3f}$"


def _write(out_dir: Path, name: str, lines: list[str]) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / name
    path.write_text(HEADER + "\n".join(lines))
    return path


def _table(caption: str, label: str, spec: str, head: str, body: list[str],
           size: str = r"\small", fit: bool = False, sep: str = "4pt") -> list[str]:
    """`fit` scales the table to the line width. No table of the paper uses it
    since the update of 2026-10-31, which sets each at a size it fits in."""
    open_, close = (r"\resizebox{\linewidth}{!}{%", r"\end{tabular}}") if fit else ("", r"\end{tabular}")
    return [r"\begin{table}[t]", r"\centering", f"\\caption{{{caption}}}", f"\\label{{{label}}}",
            size, f"\\setlength{{\\tabcolsep}}{{{sep}}}", *([open_] if open_ else []),
            f"\\begin{{tabular}}{{{spec}}}", r"\toprule", head, r"\midrule", *body,
            r"\bottomrule", close, r"\end{table}", ""]


