@dataclass(frozen=True)
class Pair:
    """MixtureVitae and one reference, each at Tulu3 SFT and after OT30K from it."""
    base_model: str
    mv_sft: str
    mv_ot3: str
    ref_sft: str
    ref_ot3: str

    @property
    def prefix(self) -> str:
        return pt.MODELS[self.base_model][1]


def pairs(m: Manifest) -> list[Pair]:
    mv = (m.checkpoint(pt.MV, "SFT-Tulu3"), m.checkpoint(pt.MV, "OT3+SFT"))
    return [Pair(bm, *mv, m.checkpoint(bm, "SFT-Tulu3"), m.checkpoint(bm, "OT3+SFT"))
            for bm in pt.REFERENCES]


def _gap(family: str, label: str, mv: str, ref: str, tasks) -> ps.Contrast:
    return ps.Contrast(family, label, ((mv, 1.0), (ref, -1.0)), tuple(tasks))


def endpoint_contrasts(prs: list[Pair]) -> list[ps.Contrast]:
    """MV minus each reference on the pooled mathematics tasks and on the
    pooled contest tasks, at Tulu3 SFT, after OT30K, and the widening between
    the two (MV's gain minus the reference's), and on IFEval after OT30K. One
    Benjamini-Hochberg family each for mathematics, contest mathematics and
    IFEval."""
    out = []
    for fam, tasks in (("math", ps.DOMAINS["math"]), ("contest", CONTEST)):
        for p in prs:
            out += [_gap(f"endpoint.{fam}", f"{p.prefix}.sft", p.mv_sft, p.ref_sft, tasks),
                    _gap(f"endpoint.{fam}", f"{p.prefix}.ot3", p.mv_ot3, p.ref_ot3, tasks),
                    ps.gain_difference(f"endpoint.{fam}", f"{p.prefix}.widening",
                                       (p.mv_ot3, p.mv_sft), (p.ref_ot3, p.ref_sft), tasks)]
    out += [_gap("endpoint.if", f"{p.prefix}.ot3", p.mv_ot3, p.ref_ot3, (ps.IFEVAL,))
            for p in prs]
    return out


def leave_one_out_contrasts(prs: list[Pair]) -> list[ps.Contrast]:
    """MV minus each reference after OT30K on the pooled mathematics tasks
    with each task left out in turn: robustness diagnostics, one family."""
    math = ps.DOMAINS["math"]
    return [_gap("endpoint.loo", f"{p.prefix}.{pt.ABBR[t].lower()}", p.mv_ot3, p.ref_ot3,
                 [x for x in math if x != t])
            for p in prs for t in math]


