def render_all(manifest_path: Path, phase2_dir: Path, out_dir: Path) -> list[Path]:
    m = Manifest.load(manifest_path)
    _, meta = p2.load(phase2_dir)
    ifeval = p2.ifeval_counts(phase2_dir)
    lengths = pd.read_parquet(inputs.path("R14-lengths", phase2_dir / "answer_lengths.parquet"))
    main = ps.Scores(m, meta, ifeval)
    sens = ps.Scores(m, meta, ifeval, runs=RUNS12)

    t2_runs = table2_runs(m)
    with_, without = exclusion_runs(m)
    runs = all_runs(m)
    results: list[tuple[str, ps.Interval]] = []

    def run(scores: ps.Scores, contrasts: list[ps.Contrast], tag: str) -> dict:
        ivs = ps.evaluate(scores, contrasts)
        results.extend((tag, iv) for iv in ivs)
        return {iv.contrast.label: iv for iv in ivs}

    t2 = run(main, table2_contrasts(m, t2_runs, "table2"), "0 1 2")
    t2_12 = run(sens, table2_contrasts(m, t2_runs, "table2.runs12"), "1 2")
    ex = run(main, exclusion_contrasts(m, with_, without, "exclusion"), "0 1 2")
    ex12 = run(sens, exclusion_contrasts(m, with_, without, "exclusion.runs12"), "1 2")
    for r in t2_runs:
        if abs(t2[r.stem].estimate - m.change(r.key)["change"]) > 1e-6:
            raise ManifestError(f"{r.key}: the records give a suite change of "
                                f"{t2[r.stem].estimate}, the manifest {m.change(r.key)['change']}.")
    dom_ivs = ps.evaluate(main, domain_contrasts(m, runs))
    results.extend(("0 1 2", iv) for iv in dom_ivs)
    dom = {(iv.contrast.family.removeprefix("domain."), iv.contrast.label): iv for iv in dom_ivs}

    prs = pairs(m)
    end_ivs = ps.evaluate(main, endpoint_contrasts(prs) + leave_one_out_contrasts(prs))
    results.extend(("0 1 2", iv) for iv in end_ivs)
    endpoint = {(iv.contrast.family, iv.contrast.label): iv for iv in end_ivs}

    shares = ae.shares(lengths, meta)
    tables_dir = out_dir / "tables"
    written = [
        endpoints_table(m, t2, tables_dir),
        change_intervals_table(t2_runs, t2, t2_12, tables_dir),
        exclusion_table(with_, without, ex, ex12, tables_dir),
        domain_table(m, runs, dom, tables_dir),
        endpoint_table(prs, endpoint, tables_dir),
        leave_one_out_table(prs, endpoint, tables_dir),
        endings_table(m, shares, "cut_off", tables_dir),
        endings_table(m, shares, "no_answer", tables_dir),
        write_macros(macros(m, runs, t2, t2_12, ex, ex12, dom, endpoint, shares), tables_dir),
    ]
    out_dir.mkdir(parents=True, exist_ok=True)
    for name, frame in (("phase2_contrasts.csv", contrasts_frame(results)),
                        ("answer_endings.csv", shares.round(4)),
                        ("length_shares.csv", ae.length_shares(lengths))):
        frame.to_csv(out_dir / name, index=False)
        written.append(out_dir / name)
    return written


def main(manifest_path: Path, phase2_dir: Path, out_dir: Path) -> int:
    try:
        written = render_all(manifest_path, phase2_dir, out_dir)
    except (ManifestError, inputs.InputError) as exc:
        print(f"error: {exc}")
        return 1
    tables = [p for p in written if p.suffix == ".tex" and p.name != "phase2_analyses_numbers.tex"]
    pdf = preview.build("Phase 2 analyses (render-phase2-analyses)", tables, [],
                        out_dir / "preview.pdf")
    for path in written + ([pdf] if pdf else []):
        print(f"  wrote {path}")
    return 0
