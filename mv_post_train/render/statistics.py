def ablation_records(manifest_path: Path, data_dir: Path) -> pd.DataFrame:
    """The 100B ablation's per-question records (R18), each checkpoint's
    `model_group` set to its ablation group, checked against the cells and
    per-seed scores of the results manifest."""
    df = pa.revision_records("R18", data_dir)
    group = {}
    for base, g in ABLATION_MODELS.items():
        for ext in ("", "-longsft_16k"):
            for stage in ("", "-SFT-Tulu3-decontaminated", "-DPO-Tulu3-decontaminated"):
                group[base + ext + stage] = g
    df = df[df["model_id"].isin(group)].copy()
    if df["model_id"].nunique() != len(group):
        raise ValueError(f"R18 has {df['model_id'].nunique()} of the {len(group)} 100B checkpoints.")
    df["model_group"] = df["model_id"].map(group)
    cells = (df.drop_duplicates("model_id")[pa.ZOO_KEYS + ["model_id"]]
             .assign(checkpoint=lambda d: d["model_id"].map(bare)).to_dict("records"))
    Manifest.load(manifest_path).check_records(df, cells, pa.ZOO_KEYS)
    return df


def mixture_ablation(df: pd.DataFrame, *, n_boot: int = N_BOOT_TABLE26
                     ) -> tuple[list[PairedContrast], list[PairedContrast]]:
    """(suite contrasts of each ablation against MV-100 in the six settings,
    per-task contrasts after SFT at 16K), with q as Table 26 computes them:
    within each column for the per-task rows, and over all suite rows."""
    pairs = [(Cell(g, ctx, stage), Cell(FULL_100B, ctx, stage))
             for stage, ctx, _ in ABLATION_CELLS for g, _, _ in ABLATIONS]
    res = paired_contrasts(df, pairs, n_boot=n_boot)
    suite = [c for c in res if c.benchmark == SUITE]
    per_task = [c for c in res if c.benchmark != SUITE and c.a.stage == "sft"
                and c.a.context_length == CTX]

    def family(found, keep):
        return [i for i, c in enumerate(found) if keep(c) and not untested(c.estimate, c.lo, c.hi)]

    for g, _, _ in ABLATIONS:
        per_task = with_q(per_task, family(per_task, lambda c: c.a.group == g))
    suite = with_q(suite, family(suite, lambda c: True))
    return suite, per_task


def mixture_ablation_table(suite: list[PairedContrast], per_task: list[PairedContrast]) -> str:
    def row(label: str, found: list[PairedContrast]) -> str:
        parts = [label]
        for g, _, _ in ABLATIONS:
            c = next(c for c in found if c.a.group == g)
            parts += cells(c.estimate, c.lo, c.hi, qfmt(c.q))
        return " & ".join(parts) + r" \\"

    lines = [HEADER, r"\begin{table}[t]", r"\centering", r"\caption{" + (
        r"Statistics for the 100B mixture-composition ablation of "
        r"Section~\ref{sec:ablations}, under Protocol~A like Table~\ref{tab:evalchemy_table1}. "
        r"Differences are the ablation minus the full 100B mixture (MV-100), in points, so "
        r"negative values mean the ablation is worse. The method is that of "
        r"Table~\ref{tab:stat-summary}: each item is scored as its mean over the three decoding "
        r"seeds, and the 95\% intervals come from the paired item-level bootstrap of "
        r"Appendix~\ref{app:stats}, with items resampled within each benchmark and 20{,}000 "
        r"replicates. $q$ is the Benjamini--Hochberg adjusted $q$-value, computed within each "
        r"column for the per-task rows and over the twelve suite-average rows. $n$ is the "
        r"number of scored items: HumanEval counts its 164 Python problems and IFEval the 769 "
        r"instructions of its 500 prompts. A dash marks a benchmark on which both models score "
        r"zero on every item, which is not tested.}"),
        r"\label{tab:stat-summary-ablation}", r"\footnotesize", r"\setlength{\tabcolsep}{3pt}",
        r"\begin{tabular}{@{}l r c l r c l@{}}", r"\toprule",
        " & " + " & ".join(rf"\multicolumn{{3}}{{c}}{{{lab} $-$ MV-100}}" for _, lab, _ in ABLATIONS)
        + r" \\",
        r"\cmidrule(l{4pt}r{4pt}){2-4} \cmidrule(l{4pt}r{4pt}){5-7}",
        r"Setting or task & $\Delta$ pp & 95\% CI & $q$ & $\Delta$ pp & 95\% CI & $q$ \\",
        r"\midrule", r"\multicolumn{7}{@{}l}{\emph{Eleven-task suite average}} \\"]
    for stage, ctx, label in ABLATION_CELLS:
        lines.append(row(label, [c for c in suite
                                 if c.a.stage == stage and c.a.context_length == ctx]))
    lines += [r"\midrule", r"\multicolumn{7}{@{}l}{\emph{Per task, after Tulu3 SFT at 16K}} \\"]
    for b in pa.BENCHMARKS:
        lines.append(row(f"{TASK_NAME[b]} ($n{{=}}{pa.BENCH_ITEMS[b]}$)",
                         [c for c in per_task if c.benchmark == b]))
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    return "\n".join(lines)


def mixture_ablation_macros(suite: list[PairedContrast],
                            per_task: list[PairedContrast]) -> dict[str, str]:
    out = {}
    key = {f: k for f, _, k in ABLATIONS}
    for c in suite:
        stem = f"abl.{key[c.a.group]}.{c.a.stage}{CTX_KEY[c.a.context_length]}.suite"
        out[stem], out[f"{stem}.lo"], out[f"{stem}.hi"] = _num(c.estimate), _num(c.lo), _num(c.hi)
        out[f"{stem}.q"] = qfmt(c.q)
    for g, _, k in ABLATIONS:   # the range over the six suite rows, as printed
        ests = [round(c.estimate, 1) for c in suite if c.a.group == g]
        out[f"abl.{k}.suite.min"], out[f"abl.{k}.suite.max"] = _num(min(ests)), _num(max(ests))
    for c in per_task:
        stem = f"abl.{key[c.a.group]}.{KEY[c.benchmark]}"
        out[stem], out[f"{stem}.lo"], out[f"{stem}.hi"] = _num(c.estimate), _num(c.lo), _num(c.hi)
        out[f"{stem}.q"] = qfmt(c.q)
    return out


