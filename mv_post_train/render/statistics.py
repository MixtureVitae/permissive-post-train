def matched_compute(df: pd.DataFrame, *, n_boot: int = N_BOOT_TABLE26
                    ) -> tuple[list[PairedContrast], list[PairedContrast], list[PairedContrast]]:
    """(per-task contrasts after SFT, suite contrasts after SFT and DPO, the
    reweighted suite contrasts after SFT), with q. Untested contrasts get no q
    and do not count in their family."""
    mv = {s: Cell("MV", CTX, s) for s in ("sft", "dpo")}
    pairs = [(mv[s], Cell(g, CTX, s)) for s in ("sft", "dpo") for g, _, _ in OPPONENTS]
    res = paired_contrasts(df, pairs, n_boot=n_boot, views=domain_views())
    per_task = [c for c in res if c.a.stage == "sft" and c.benchmark in pa.BENCHMARKS]
    suite = [c for c in res if c.benchmark == SUITE]
    views = [c for c in res if c.a.stage == "sft" and c.benchmark in VIEW_LABEL]

    def family(found, keep):
        return [i for i, c in enumerate(found) if keep(c) and not untested(c.estimate, c.lo, c.hi)]

    for g, _, _ in OPPONENTS:   # one family per column of the per-task block
        per_task = with_q(per_task, family(per_task, lambda c: c.b.group == g))
    suite = with_q(suite, family(suite, lambda c: True))
    views = with_q(views, family(views, lambda c: True))
    return per_task, suite, views


def matched_compute_table(per_task: list[PairedContrast], suite: list[PairedContrast],
                          views: list[PairedContrast]) -> str:
    def row(label: str, found: list[PairedContrast]) -> str:
        parts = [label]
        for g, _, _ in OPPONENTS:
            c = next(c for c in found if c.b.group == g)
            parts += cells(c.estimate, c.lo, c.hi, qfmt(c.q))
        return " & ".join(parts) + r" \\"

    lines = [HEADER, r"\begin{table}[t]", r"\centering", r"\caption{" + (
        r"Phase~1 matched-compute contrasts under Protocol~A at 16K context. Differences are "
        r"MV minus the reference, in points, so positive values favour MV. Each item is scored "
        r"as its mean over the three decoding seeds, and the 95\% intervals come from the paired "
        r"item-level bootstrap of Appendix~\ref{app:stats}, with items resampled within each "
        r"benchmark. This table uses 20{,}000 replicates rather than 2{,}000, so that its "
        r"$q$-values are not limited by the smallest $p$-value the bootstrap can give. $q$ is "
        r"the Benjamini--Hochberg adjusted $q$-value, computed within each column for the "
        r"per-task rows, over the four suite-average rows, and over the ten reweighted rows. "
        r"The reweighted rows recompute the suite average after SFT with the four domains of "
        r"Table~\ref{tab:eval-settings-A} weighted equally, or with one domain left out, as "
        r"Table~\ref{tab:domain_robustness} does for the front-loading study. "
        r"$n$ is the number of scored "
        r"items: HumanEval counts its 164 Python problems and IFEval the 769 instructions of "
        r"its 500 prompts. A dash marks a benchmark on which both models score zero on every "
        r"item, which is not tested.}"),
        r"\label{tab:stat-summary}", r"\footnotesize", r"\setlength{\tabcolsep}{3pt}",
        r"\begin{tabular}{@{}l r c l r c l@{}}", r"\toprule",
        " & " + " & ".join(rf"\multicolumn{{3}}{{c}}{{MV $-$ {lab}}}" for _, lab, _ in OPPONENTS)
        + r" \\",
        r"\cmidrule(l{4pt}r{4pt}){2-4} \cmidrule(l{4pt}r{4pt}){5-7}",
        r"Task & $\Delta$ pp & 95\% CI & $q$ & $\Delta$ pp & 95\% CI & $q$ \\", r"\midrule",
        r"\multicolumn{7}{@{}l}{\emph{Per task, after Tulu3 SFT}} \\"]
    for b in pa.BENCHMARKS:
        lines.append(row(f"{TASK_NAME[b]} ($n{{=}}{pa.BENCH_ITEMS[b]}$)",
                         [c for c in per_task if c.benchmark == b]))
    lines += [r"\midrule", r"\multicolumn{7}{@{}l}{\emph{Eleven-task suite average}} \\"]
    for s in ("sft", "dpo"):
        lines.append(row(STAGE_LABEL[s], [c for c in suite if c.a.stage == s]))
    lines += [r"\midrule",
              r"\multicolumn{7}{@{}l}{\emph{Suite average reweighted, after Tulu3 SFT}} \\"]
    for view, label in VIEW_LABEL.items():
        lines.append(row(label, [c for c in views if c.benchmark == view]))
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    return "\n".join(lines)


def matched_compute_macros(per_task: list[PairedContrast], suite: list[PairedContrast],
                           views: list[PairedContrast]) -> dict[str, str]:
    """Keys of Table 26, for `\\pstat{<key>}`:
      mc.<opp>.<task>[.lo/.hi/.q/.level]       a per-task row, after SFT
      mc.<stage>.<opp>.suite[.lo/.hi/.q/.level]   a suite-average row
      mc.sft.<opp>.<view>[.lo/.hi/.q/.level]    a reweighted row, with `view` as in
          pairwise_a.domain_views
      mc.sft.reweighted.min/.max   the range of the ten reweighted rows, as printed
      mc.sft.reweighted.lo.min     the lowest lower bound of their intervals"""
    out = {}
    key = {g: k for g, _, k in OPPONENTS}
    for c in per_task:
        stem = f"mc.{key[c.b.group]}.{KEY[c.benchmark]}"
        out[stem] = _num(c.estimate)
        out[f"{stem}.lo"], out[f"{stem}.hi"] = _num(c.lo), _num(c.hi)
        out[f"{stem}.q"] = qfmt(c.q)
        out[f"{stem}.level"] = f"{c.level_b:.1f}"
        out[f"mc.mv.{KEY[c.benchmark]}.level"] = f"{c.level_a:.1f}"
    for c in suite:
        stem = f"mc.{c.a.stage}.{key[c.b.group]}.suite"
        out[stem] = _num(c.estimate)
        out[f"{stem}.lo"], out[f"{stem}.hi"] = _num(c.lo), _num(c.hi)
        out[f"{stem}.q"] = qfmt(c.q)
        out[f"{stem}.level"] = f"{c.level_b:.1f}"
        out[f"mc.{c.a.stage}.mv.suite.level"] = f"{c.level_a:.1f}"
    for c in views:
        stem = f"mc.sft.{key[c.b.group]}.{c.benchmark}"
        out[stem] = _num(c.estimate)
        out[f"{stem}.lo"], out[f"{stem}.hi"] = _num(c.lo), _num(c.hi)
        out[f"{stem}.q"] = qfmt(c.q)
        out[f"{stem}.level"] = f"{c.level_b:.1f}"
        out[f"mc.sft.mv.{c.benchmark}.level"] = f"{c.level_a:.1f}"
    est = [round(c.estimate, 1) for c in views]
    out["mc.sft.reweighted.min"], out["mc.sft.reweighted.max"] = _num(min(est)), _num(max(est))
    out["mc.sft.reweighted.lo.min"] = _num(min(round(c.lo, 1) for c in views))
    return out


