def write_macros(values: dict[str, str], path: Path) -> Path:
    lines = [
        HEADER,
        "% Numbers for the text of the statistics appendix, from the same values as Tables 26",
        r"% and 27. Use \pstat{<key>}, for example \pstat{mc.comma.m500}. A key that does not",
        "% exist prints in bold between question marks.",
    ]
    lines += macro_lines("pstat", values, sort=True)
    path.write_text("\n".join(lines) + "\n")
    return path


def zoo_records(manifest_path: Path, data_dir: Path) -> pd.DataFrame:
    """The per-question records of Phase 1 (R13), which Table 26 resamples,
    checked against the cells and per-seed scores of the results manifest's
    `phase1_zoo` design."""
    m = Manifest.load(manifest_path)
    df = pa.zoo(pa.revised_reasoning(data_dir))
    m.check_records(df, m.design("phase1_zoo")["cells"], pa.ZOO_KEYS)
    return df


def render_all(manifest_path: Path, data_dir: Path, out_dir: Path) -> list[Path]:
    df = zoo_records(manifest_path, data_dir)
    per_task, suite, views = matched_compute(df)
    abl_suite, abl_task = mixture_ablation(ablation_records(manifest_path, data_dir))
    mde = power(per_task, out_dir / "power.csv")
    tables = out_dir / "tables"
    tables.mkdir(parents=True, exist_ok=True)
    written = []
    for name, body in (("stat_matched_compute.tex", matched_compute_table(per_task, suite, views)),
                       ("stat_mixture_ablation.tex", mixture_ablation_table(abl_suite, abl_task))):
        (tables / name).write_text(body)
        written.append(tables / name)
    macros = {**matched_compute_macros(per_task, suite, views), **power_macros(mde),
              **mixture_ablation_macros(abl_suite, abl_task)}
    written.append(write_macros(macros, tables / "statistics_numbers.tex"))
    mde.to_csv(out_dir / "power.csv", index=False)
    written.append(out_dir / "power.csv")
    return written


def main(manifest_path: Path, data_dir: Path, out_dir: Path) -> int:
    written = render_all(manifest_path, data_dir, out_dir)
    tables = [p for p in written if p.suffix == ".tex" and p.name != "statistics_numbers.tex"]
    pdf = preview.build("Statistics appendix (render-statistics)", tables, [],
                        out_dir / "preview.pdf")
    for path in written + ([pdf] if pdf else []):
        print(f"  wrote {path}")
    return 0
