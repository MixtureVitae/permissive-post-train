"""The statistics appendix of the paper: Tables 26 and 27, and the numbers its
text quotes (`mvpt render-statistics`).

Table 26 (`tab:stat-summary`) compares MV-16K with the two matched-compute
references the text discusses, Comma0.1-16K and Nemotron-CC-HQ-16K, under
Protocol A. It reads the per-question records (R13) and uses the paired
item-level bootstrap of `stats/pairwise_a.py`, the method of the appendix
`app:stats`, with 20,000 replicates instead of Table 28's 2,000. With 2,000,
the smallest p-value is 1/2,000, and a column's q-values then depend on how
many of its tests sit at that floor rather than on the data. Its last block
reweights the suite average after SFT by domain (`pairwise_a.domain_views`),
the views of Table 29, which the authors promised the reviewers for MV against
the references. Those ten contrasts are one q-value family. It replaces the
older single-run version, which used a 12-task suite with a pipeline bug.

Table 27 (`tab:stat-summary-ablation`) is the 100B mixture ablation, under
Protocol A like Table 7. It reads the per-question records of the older
experiments (R18) and uses the same method as Table 26: the paired item-level
bootstrap with 20,000 replicates, each item scored as its mean over the three
seeds, and Benjamini-Hochberg q-values within each column of the per-task rows
and over the suite-average rows. The records' labels call every 100B variant
"MV", so the checkpoints are told apart by name (ABLATION_MODELS), and both
record files are checked against the results manifest.

The power figures are the minimum detectable effect of each benchmark of
Table 26, at its Protocol A size and at the references' own score
(`stats.core.mde_paired_binomial`, one outcome per item and a sign-flip test).

Writes, under results/statistics/:
  tables/stat_matched_compute.tex   Table 26
  tables/stat_mixture_ablation.tex  Table 27
  tables/statistics_numbers.tex     \\pstat{<key>} macros for the text
  power.csv                         the minimum detectable effects and their settings
  preview.pdf
"""
