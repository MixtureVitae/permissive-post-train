# Power


def power(per_task: list[PairedContrast], cache: Path | None = None) -> pd.DataFrame:
    """Minimum detectable effect for each benchmark of Table 26, at the mean
    score of the two references, with MDE_SETTINGS: 80% power, a two-sided 5%
    level, and a correlation of 0.3 between the two models' 0/1 outcomes on an
    item, under a sign-flip test on one outcome per item. Table 26 tests
    seed-averaged items with the bootstrap, so these figures describe a
    single-run design. The simulation takes minutes, so rows of `cache` (a
    previous power.csv) are reused when the benchmark, size, baseline and
    every setting match."""
    old = {}
    if cache is not None and cache.exists():
        prev = pd.read_csv(cache)
        if set(MDE_SETTINGS) <= set(prev.columns):
            for r in prev.to_dict("records"):
                if all(r[k] == v for k, v in MDE_SETTINGS.items()):
                    old[(r["benchmark"], r["n"], r["baseline_pp"])] = r["mde_pp"]
    rows = []
    for b in pa.BENCHMARKS:
        base = round(sum(c.level_b for c in per_task if c.benchmark == b) / len(OPPONENTS), 2)
        mde = old.get((b, pa.BENCH_ITEMS[b], base))
        if mde is None:
            mde = round(mde_paired_binomial(base / 100.0, pa.BENCH_ITEMS[b], **MDE_SETTINGS)[0]
                        * 100.0, 1)
        rows.append({"benchmark": b, "n": pa.BENCH_ITEMS[b], "baseline_pp": base,
                     "mde_pp": mde, **MDE_SETTINGS})
    return pd.DataFrame(rows)


def power_macros(mde: pd.DataFrame) -> dict[str, str]:
    out = {}
    for r in mde.itertuples():
        out[f"mde.{KEY[r.benchmark]}"] = f"{r.mde_pp:.0f}"
        out[f"mde.{KEY[r.benchmark]}.baseline"] = f"{r.baseline_pp:.1f}"
    return out


