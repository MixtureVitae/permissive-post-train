CTX = 16384
#: Replicates for Table 26. See the module docstring.
N_BOOT_TABLE26 = 20_000
#: (Phase 1 group, label in the table, key in the macros)
OPPONENTS = (("Comma0.1", "Comma0.1", "comma"), ("Nemotron", "Nemotron-CC-HQ", "nemotron"))
#: (ablation group, label, key), each against the full 100B mixture, MV-100
ABLATIONS = (("MV-noweb", "MV-noweb", "noweb"), ("MV-noinst", "MV-noinstruct", "noinst"))
FULL_100B = "MV-100"
#: The 100B checkpoints' base names in R18 -> their group here. The 16K, SFT
#: and DPO checkpoints follow from the names.
ABLATION_MODELS = {"ali-elganzory/1.7b-MixtureVitae-100BT": FULL_100B,
                   "ali-elganzory/1.7b-MixtureVitae-curated_instruct-100BT": "MV-noweb",
                   "ali-elganzory/1.7b-MixtureVitae-web_curated-100BT": "MV-noinst"}
ABLATION_CELLS = (("base", 4096, "Base, 4K"), ("sft", 4096, "Tulu3 SFT, 4K"),
                  ("dpo", 4096, r"SFT$\to$DPO, 4K"), ("base", CTX, "Base, 16K"),
                  ("sft", CTX, "Tulu3 SFT, 16K"), ("dpo", CTX, r"SFT$\to$DPO, 16K"))
CTX_KEY = {4096: "4k", CTX: "16k"}
#: Settings of the power simulation. power.csv records them, and a cached row
#: is reused only when they all match.
MDE_SETTINGS = {"target_bernoulli_rho": 0.3, "alpha": 0.05, "target_power": 0.8,
                "n_trials": 1000, "n_perm": 1000, "seed": 0}
STAGE_LABEL = {"sft": "Tulu3 SFT, 16K", "dpo": r"SFT$\to$DPO, 16K"}
TASK_NAME = {"AIME24": "AIME24", "AIME25": "AIME25", "AMC23": "AMC23", "MATH500": "MATH500",
             "gsm8k": "GSM8K", "HumanEval": "HumanEval", "LiveCodeBench": "LiveCodeBench",
             "MBPP": "MBPP", "GPQADiamond": "GPQA-Diamond", "JEEBench": "JEEBench",
             "IFEval": "IFEval"}
KEY = {b: pa.BENCH_ABBR[b].lower() for b in pa.BENCHMARKS}
#: The reweighted suite averages of Table 26, as Table 29 labels them.
VIEW_LABEL = {"equal_domain": "Equal-domain average", "drop_math": "Drop math domain",
              "drop_code": "Drop code domain", "drop_science": "Drop science domain",
              "drop_instruction": "Drop instruction domain"}



def is_degenerate(d: float, lo: float, hi: float) -> bool:
    """Both models scored 0 on every item, so the paired bootstrap has no
    signal. Such a cell prints a dash, not "+0.0 [+0.0, +0.0]"."""
    return d == 0.0 and lo == 0.0 and hi == 0.0


def qfmt(q: float) -> str:
    """As Table 28 prints q-values."""
    if pd.isna(q):
        return "--"
    return r"$<0.001$" if q < 0.001 else f"${q:.3f}$"


def signed(x: float) -> str:
    return f"{round(x, 1) + 0.0:+.1f}"


def untested(est: float, lo: float, hi: float) -> bool:
    """Both models score zero on every item, so there is nothing to test."""
    return is_degenerate(round(est, 6), round(lo, 6), round(hi, 6))


def cells(est: float, lo: float, hi: float, sig: str) -> list[str]:
    if untested(est, lo, hi):
        return ["---", "---", "---"]
    return [f"${signed(est)}$", f"$[{signed(lo)},\\,{signed(hi)}]$", sig]


def _num(x: float) -> str:
    return f"\\ensuremath{{{signed(x)}}}"


