def results_lines(s: pd.DataFrame, n_left: int) -> list[str]:
    def get(analysis: str, family: str, label: str):
        x = s[(s["analysis"] == analysis) & (s["family"] == family) & (s["label"] == label)]
        if len(x) != 1:
            raise ValueError(f"O2 has {len(x)} rows for {analysis} {family} {label}")
        return x.iloc[0]
    picks = (
        (r"MV SFT$\to$OT30K, MATH500", get("phase2", "table2.m500", "mv.sft-ot3")),
        (r"MV SFT$\to$OT30K, suite average", get("phase2", "table2.avg", "mv.sft-ot3")),
        ("OT3-source exclusion, difference of MATH500 gains",
         get("phase2", "exclusion", "difference.m500")),
        ("OT3-source exclusion, difference of suite-average gains",
         get("phase2", "exclusion", "difference.avg")),
        (r"MV SFT$\to$OT30K, language average",
         get("language", "change.avg", "mv | mv.sft-ot3 | mv.sft")),
    )
    rows = [f"{n} & {cell(r.estimate, r.lo, r.hi, d)} & "
            f"{cell(r.estimate_cut, r.lo_cut, r.hi_cut, d)} \\\\"
            for n, r in picks for d in [2 if r.analysis == "language" else 1]]
