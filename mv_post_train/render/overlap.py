def render_all(manifest_path: Path, phase2_dir: Path, out_dir: Path) -> list[Path]:
    drop = excluded_items()
    s = sensitivity()
    f = found()
    check_found(f, drop)
    it = items_table(f)
    rates = corpus_rates()
    t4 = recompute_table4(manifest_path, phase2_dir, drop, s)
    tok, unfinished = tokens(), ot3_unfinished()
    n_left = int(it.loc[it["benchmark"] == pt.HELDOUT_TASK, "left"].iloc[0])
    tables = out_dir / "tables"
    tables.mkdir(parents=True, exist_ok=True)
    written = []
    for fname, lines in (("heldout_reasoning_retained.tex", table4_retained(t4, n_left)),
                         ("overlap_coverage.tex", coverage_table()),
                         ("overlap_items.tex", items_lines(it)),
                         ("overlap_results.tex", results_lines(s, n_left)),
                         ("overlap_summary.tex", summary_lines(s)),
                         ("overlap_calls.tex", calls_lines(s)),
                         ("corpus_overlap.tex", corpus_lines(rates)),
                         ("phase2_tokens.tex", tokens_lines(tok, unfinished))):
        path = tables / fname
        path.write_text(HEADER + "\n".join(lines))
        written.append(path)
    written.append(write_macros(macros(s, t4, it, rates, tok, unfinished),
                                tables / "overlap_numbers.tex"))
    return written


def main(manifest_path: Path, phase2_dir: Path, out_dir: Path) -> int:
    written = render_all(manifest_path, phase2_dir, out_dir)
    tables = [p for p in written if p.name != "overlap_numbers.tex"]
    pdf = preview.build("The benchmark-overlap audit (render-overlap)", tables, [],
                        out_dir / "preview.pdf", preamble="\\usepackage{bm}\n")
    for path in written + ([pdf] if pdf else []):
        print(f"  wrote {path}")
    return 0
