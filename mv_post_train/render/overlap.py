    other = ("general", "instruction_following")
    rows = []
    for corpus in ("OpenThoughts3", "AceReason", "Nemotron-Cascade", "Superior-Reasoning"):
        x = rates[rates["corpus"] == corpus].set_index("subset")
        cells = [f"{x.loc[d, 'found']:.1f}" if d in x.index else "--" for d in domains]
        rest = [f"{x.loc[d, 'found']:.1f}" for d in other if d in x.index]
        rows.append(f"{corpus} & {count(int(x.loc['all', 'questions']))} & "
                    f"{x.loc['all', 'found']:.1f} & " + " & ".join(cells) + " & "
                    + (" / ".join(rest) if rest else "--") + r" \\")
    caption = (
        r"\textbf{The Phase 2 samples' questions in MixtureVitae's reasoning pool.} Percent of the "
        r"questions of each 30K sample trained on that match a document of MixtureVitae's "
        r"pretraining reasoning data other than OpenThoughts3, overall and by domain (13-gram and "
        r"exact matching, Appendix~\ref{app:decontam}). Other is general questions for "
        r"Nemotron-Cascade and instruction following for Superior-Reasoning. The model "
        r"pretrained without the OpenThoughts3 source keeps this data, so the OT3-source "
        r"exclusion keeps most of the Phase 2 OpenThoughts3 mathematics problems, with other "
        r"solutions. A match is a document of the pool, not evidence that a 300B-token run "
        r"drew it.")
    return _table(caption, "tab:corpus_overlap", "lrrrrrr",
                  [r"Corpus & Questions & All & Math & Code & Science & Other \\"], rows)


