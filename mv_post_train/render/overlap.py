def ot3_unfinished(release: pd.DataFrame | None = None) -> float:
    """Percent of the OT3 30K answers as released that never close their reasoning."""
    r = release if release is not None else pd.read_csv(inputs.path("O7"))
    a = r[r["domain"] == "all"]
    return 100.0 - float((a["think_end"] * a["samples"]).sum() / a["samples"].sum())


def billions(n: float) -> str:
    return f"{n / 1e9:.2f}B"


def check_found(f: pd.DataFrame, drop: dict[str, set[str]]) -> None:
    """O1 must be exactly the items O3 found with evidence that leaves them out."""
    g = f[f["evidence"].isin(LEFT_OUT)]
    ids = {b: set(x["item"]) for b, x in g.groupby("benchmark")}
    if ids != drop:
        raise ValueError("O1 is not the set of items O3 found with the evidence left out.")
    unknown = set(drop) - set(BENCHMARKS)
    if unknown:
        raise ValueError(f"benchmarks with items found but no size here: {sorted(unknown)}")


def column(where: str) -> str | None:
    if where in REASONING_QUESTIONS:
        return "questions"
    if where.startswith("phase2:"):
        return "phase2:"
    if where.startswith("sample:"):
        return None
    return where


def items_table(f: pd.DataFrame) -> pd.DataFrame:
    """Per benchmark: items, items found, items left, and items found in each
    training dataset of WHERE."""
    g = f[f["evidence"].isin(LEFT_OUT)].assign(col=f["where"].map(column))
    by = g.dropna(subset=["col"]).groupby(["benchmark", "col"])["item"].nunique().unstack(
        fill_value=0)
    rows = []
    for b, (name, n) in BENCHMARKS.items():
        k = g.loc[g["benchmark"] == b, "item"].nunique()
        rows.append(dict(benchmark=b, name=name, items=n, found=k, left=n - k,
                         **{c: int(by.loc[b, c]) if b in by.index and c in by.columns else 0
                            for c, _ in WHERE}))
    out = pd.DataFrame(rows).sort_values(["found", "items"], ascending=[False, True])
    if (out["found"] > out["items"]).any():
        raise ValueError("a benchmark has more items found than items")
    return out.reset_index(drop=True)


def recompute_table4(manifest_path: Path, phase2_dir: Path, drop: dict[str, set[str]],
                     s: pd.DataFrame) -> pd.DataFrame:
    """Table 4's changes on all problems and without O1's, recomputed from the
    records, and checked against O2's."""
    from ..stats import overlap_sensitivity as os_
    t4 = os_.table4(manifest_path, phase2_dir, drop)
    ref = s[s["analysis"] == "table4"].set_index("label")
    cols = ["estimate", "lo", "hi", "q", "estimate_cut", "lo_cut", "hi_cut", "q_cut"]
    for r in t4.itertuples():
        theirs = ref.loc[r.label, cols]
        for c in cols:
            if abs(getattr(r, c) - theirs[c]) > 1e-3:
                raise ValueError(f"Table 4, {r.label}, {c}: recomputed {getattr(r, c):.4f}, "
                                 f"O2 has {theirs[c]:.4f}.")
    return t4


