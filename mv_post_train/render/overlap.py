def macros(s: pd.DataFrame, t4: pd.DataFrame, it: pd.DataFrame, rates: pd.DataFrame,
           tok: pd.DataFrame, unfinished: float) -> dict[str, str]:
    v: dict[str, str] = {}
    m = lambda x: f"\\ensuremath{{{signed(x)}}}"
    iv = lambda lo, hi: f"\\ensuremath{{{interval(lo, hi)}}}"
    # the audit
    v["items.found"] = count(int(it["found"].sum()))
    v["benchmarks.found"] = number_word(len(it))
    for _, r in it.iterrows():
        k = r["benchmark"].lower()
        for c in ("items", "found", "left"):
            v[f"{k}.{c}"] = count(int(r[c]))
        for c, _ in WHERE:
            v[f"{k}.{c.rstrip(':').replace('_decontaminated', '')}"] = count(int(r[c]))
    # Phase 2
    def row(analysis, family, label):
        x = s[(s["analysis"] == analysis) & (s["family"] == family) & (s["label"] == label)]
        return x.iloc[0]
    for key, (analysis, family, label) in {
            "mv.sft-ot3.m500": ("phase2", "table2.m500", "mv.sft-ot3"),
            "mv.sft-ot3.avg": ("phase2", "table2.avg", "mv.sft-ot3"),
            "exclusion.difference.m500": ("phase2", "exclusion", "difference.m500"),
            "exclusion.difference.avg": ("phase2", "exclusion", "difference.avg"),
            "lang.mv.sft-ot3": ("language", "change.avg", "mv | mv.sft-ot3 | mv.sft")}.items():
        r = row(analysis, family, label)
        if analysis == "language":
            f2 = lambda x: f"\\ensuremath{{{x:+.2f}}}"
            v[f"{key}.full"], v[key] = f2(r.estimate), f2(r.estimate_cut)
            v[f"{key}.full.ci"] = f"\\ensuremath{{[{r.lo:+.2f}, {r.hi:+.2f}]}}"
            v[f"{key}.ci"] = f"\\ensuremath{{[{r.lo_cut:+.2f}, {r.hi_cut:+.2f}]}}"
            v[f"{key}.lo"], v[f"{key}.hi"] = f2(r.lo_cut), f2(r.hi_cut)
            continue
        v[f"{key}.full"] = m(r.estimate)
        v[f"{key}.full.abs"] = f"{abs(pt.printed(r.estimate)):.1f}"
        v[f"{key}.full.ci"] = iv(r.lo, r.hi)
        v[key] = m(r.estimate_cut)
        v[f"{key}.abs"] = f"{abs(pt.printed(r.estimate_cut)):.1f}"
        v[f"{key}.ci"] = iv(r.lo_cut, r.hi_cut)
        v[f"{key}.lo"] = m(r.lo_cut)
        v[f"{key}.hi"] = m(r.hi_cut)
    # Table 4
    cut = {tuple(x.strip() for x in r.label.split("|")): r for r in t4.itertuples()}
    for corpus, prefix in pt.CORPORA:
        r = cut[(pt.MV, corpus)]
        v[f"t4.mv.{prefix.lower()}"] = m(r.estimate_cut)
        v[f"t4.mv.{prefix.lower()}.full"] = m(r.estimate)
    alt = [cut[(pt.MV, c)].estimate_cut for c, _ in pt.CORPORA[1:]]
    v["t4.mv.alt.min"], v["t4.mv.alt.max"] = m(min(alt)), m(max(alt))
    if not all(cut[(pt.MV, c)].lo_cut > 0 and cut[(pt.MV, c)].q_cut < SIGNIFICANCE
               for c, _ in pt.CORPORA):
        raise ValueError("Table 4: a MixtureVitae gain is no longer significant without the items.")
    refs = [(b, c) for b in ("Comma0.1-1.7B", "FineWebEdu-1.7B", "NemotronHQ-1.7B")
            for c, _ in pt.CORPORA]
    b, c = max(refs, key=lambda k: cut[k].estimate_cut)
    v["t4.ref.max"] = m(cut[(b, c)].estimate_cut)
    v["t4.ref.max.who"] = f"{pt.MODELS[b][0]} under {c}"
    v["t4.n"] = number_word(len(t4))
    v["comparisons.n"] = count(len(s))
    # counts of comparisons and calls
    for analysis, family, title in FAMILIES:
        x = select(s, analysis, family)
        k = f"{analysis}.{family.replace('.*', '.tasks')}"
        v[f"calls.{k}"] = number_word(int(changed(x).sum()))
        v[f"maxchange.{k}"] = f"{(x['estimate_cut'] - x['estimate']).abs().max():.2f}"
    fac = s[s["analysis"] == "factorial"]
    v["calls.factorial"] = number_word(int(changed(fac).sum()))
    lang_avg = s[(s["analysis"] == "language") & s["family"].str.endswith(".avg")]
    v["calls.language.avg"] = number_word(int(changed(lang_avg).sum()))
    v["maxchange.language.avg"] = f"{(lang_avg['estimate_cut'] - lang_avg['estimate']).abs().max():.2f}"
    p2 = s[s["analysis"].isin(["phase2", "table4"]) & s["family"].isin(
        ["table2.m500", "table4.m500"])]
    v["maxchange.phase2.m500"] = f"{(p2['estimate_cut'] - p2['estimate']).abs().max():.1f}"
    # the front-loading effects after post-training, without the items
    fl = fac[(fac["family"] == "front-loading") & ~fac["label"].str.endswith("base")]
    if not ((fl["q_cut"] < SIGNIFICANCE) & (fl["estimate_cut"] > 0)).all():
        raise ValueError("A front-loading effect after post-training is no longer significant "
                         "without the items, but §3.2 says that the benefit persists.")
    v["fl.post.n"] = number_word(len(fl))
    v["fl.post.min"], v["fl.post.max"] = m(fl["estimate_cut"].min()), m(fl["estimate_cut"].max())
    # the reasoning corpora in MixtureVitae's pool
    a = rates[(rates["subset"] == "all") & (rates["corpus"] != "OpenThoughts3")]
    v["corpus.alt.min"], v["corpus.alt.max"] = f"{a['found'].min():.1f}", f"{a['found'].max():.1f}"
    o = rates[rates["corpus"] == "OpenThoughts3"].set_index("subset")
    v["corpus.ot3.math"], v["corpus.ot3.all"] = f"{o.loc['math', 'found']:.1f}", f"{o.loc['all', 'found']:.1f}"
    # the training tokens of the Phase 2 samples
    v["tokens.min"], v["tokens.max"] = billions(tok["sup_run"].min()), billions(tok["sup_run"].max())
    v["tokens.ot3.truncated"] = f"{tok.loc['OpenThoughts3', 'at_cutoff']:.1f}"
    v["tokens.ot3.unfinished"] = f"{unfinished:.1f}"
    return v


def write_macros(values: dict[str, str], path: Path) -> Path:
    lines = [HEADER.rstrip("\n"),
             "% Numbers for the text, from the benchmark-overlap audit and its comparisons.",
             r"% Use \povl{<key>}, for example \povl{mv.sft-ot3.m500} or \povl{math500.left}.",
             "% A key that does not exist prints in bold between question marks."]
    lines += macro_lines("povl", values)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")
    return path


