def _table(caption: str, label: str, spec: str, head: list[str], rows: list[str],
           size: str = r"\footnotesize", star: bool = False) -> list[str]:
    env = "table*" if star else "table"
    return [f"\\begin{{{env}}}[t]", r"\centering", f"\\caption{{{caption}}}",
            f"\\label{{{label}}}", size, r"\setlength{\tabcolsep}{4pt}",
            f"\\begin{{tabular}}{{{spec}}}", r"\toprule", *head, r"\midrule", *rows,
            r"\bottomrule", r"\end{tabular}", f"\\end{{{env}}}", ""]


def table4_retained(t4: pd.DataFrame, n_left: int) -> list[str]:
    values = {}
    for r in t4.itertuples():
        base, corpus = (x.strip() for x in r.label.split("|"))
        values[(base, corpus)] = (r.estimate_cut, r.lo_cut, r.hi_cut, r.q_cut)
    caption = (
        r"\textbf{The reasoning gain is not tied to OpenThoughts3.} Change in MATH500 accuracy "
        r"when each base's Tulu3 SFT checkpoint receives 30K samples from one of four reasoning "
        f"corpora, on the common {n_left}-problem subset left after excluding the identified "
        r"overlaps (Section~\ref{sec:methods-decontam}). The corpora are distinct releases but "
        r"overlap with MixtureVitae's pretraining pool, and the runs match examples and epochs, not "
        r"supervised tokens. Brackets are 95\% paired bootstrap intervals. \textbf{Bold} and "
        r"\emph{italic} mark significant increases and decreases after Benjamini--Hochberg "
        rf"correction over the {len(t4)} changes. Appendix Table~\ref{{tab:heldout_reasoning_full}} "
        r"gives all 500 problems. Protocol~B (Appendix Table~\ref{tab:eval-settings-B}).")
    return pt.heldout_lines(values, caption, "tab:heldout_reasoning")


