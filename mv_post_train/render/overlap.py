# Formatting


def signed(x: float) -> str:
    """A change with one decimal and its sign, for math mode."""
    return f"{pt.printed(x):+.1f}"


def interval(lo: float, hi: float) -> str:
    return f"[{signed(lo)}, {signed(hi)}]"


def cell(estimate: float, lo: float, hi: float, digits: int = 1) -> str:
    f = (lambda x: signed(x)) if digits == 1 else (lambda x: f"{x:+.{digits}f}")
    return f"${f(estimate)}$ {{\\scriptsize$[{f(lo)}, {f(hi)}]$}}"


def q_text(q: float) -> str:
    return "$<$0.001" if q < 0.001 else f"{q:.3f}"


def count(n: int) -> str:
    return f"{n:,}".replace(",", "{,}")


def changed(s: pd.DataFrame) -> pd.Series:
    sig = lambda q: q < SIGNIFICANCE - 1e-9
    return sig(s["q"]) != sig(s["q_cut"])


def select(s: pd.DataFrame, analysis: str, family: str) -> pd.DataFrame:
    x = s[s["analysis"] == analysis]
    if family.endswith(".*"):
        stem = family[:-1]
        return x[x["family"].str.startswith(stem) & ~x["family"].str.endswith(".avg")]
    return x[x["family"] == family]


def name(row) -> str:
    """A comparison of O2, in words."""
    a, fam, label = row.analysis, row.family, row.label
    if a == "phase2" and fam.startswith("table2."):
        fam_key, stage = label.split(".", 1)
        what = "suite average" if fam.endswith(".avg") else "MATH500"
        return f"{FAMILY_NAMES[fam_key]} {STAGES[stage]}, {what}"
    if a == "phase2":
        part, task = label.rsplit(".", 1)
        part = {"with-ot3": "gain with the OT3 source", "without-ot3": "gain without it",
                "difference": "difference of gains"}[part]
        return f"OT3-source exclusion, {part}, {'MATH500' if task == 'm500' else 'suite average'}"
    if a == "table4":
        base, corpus = (x.strip() for x in label.split("|"))
        return f"{pt.MODELS[base][0]} SFT$\\to${corpus}, MATH500"
    if a == "factorial":
        who, ctx, stage = (x.strip() for x in label.split("|"))
        who = " $-$ ".join(POOLS[p.strip()] for p in who.split(" - "))
        kind = {"front-loading": "Front-loading", "permissiveness": "Source pools",
                "interaction": "Interaction"}[fam]
        return f"{kind}, {who}, {CONTEXTS[ctx]}, {STAGES.get(stage, stage)}"
    parts = [x.strip() for x in label.split("|")]
    if fam.startswith("change."):
        fam_key = parts[0]
        child, parent = (p.split(".", 1)[1] for p in parts[1:])
        return f"{FAMILY_NAMES[fam_key]} {STAGES[child]}, from {STAGES[parent]}, language"
    kind, ctx, who = parts
    who = " $-$ ".join(POOLS[p.strip()] for p in who.split(" - "))
    kind = {"front-loading": "Front-loading", "permissiveness": "Source pools",
            "interaction": "Interaction"}[kind]
    return f"{kind}, {who}, {CONTEXTS[ctx]} base, language"


