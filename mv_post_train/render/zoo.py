"""Tables 1 and 6 of the revision, Phase 1 for all models, and their text macros.

`mvpt render-zoo` writes, from the Protocol A results of the results manifest
(its `phase1_zoo` design names the checkpoint of each cell):

  <out-dir>/tables/phase1_zoo.tex        Table 1: one context variant per family
  <out-dir>/tables/phase1_zoo_full.tex   Table 6: both context variants
  <out-dir>/tables/zoo_numbers.tex       \\pzoo{<key>} macros for the text
  <out-dir>/preview.pdf                  both tables, compiled

Table 6 is the one `mvpt render-workshop` writes for the workshop paper, with
the main revision's caption. Table 1 has a layout of its own (`phase1_table`),
and `check_claims` stops the render if a claim the abstract makes about it in
words no longer holds. Every number is the mean over the three
decoding seeds, and the suite average is the mean of the 11 task scores of
each seed, then averaged over the seeds (stats/factorial.py).

Macro keys are `<family>.<context>.<stage>.<task>`, for example
`mv.16k.base.avg` or `qwen3.16k.dpo.m500`, with `.sd` for the standard
deviation over seeds.
"""
from __future__ import annotations

import math
from pathlib import Path

import pandas as pd

from ..data import protocol_a as pa
from ..manifest.reader import Manifest
from ..stats import factorial as fs
from . import preview
from . import workshop_tables as wt
from .macros import macro_lines

HEADER = "% Generated by `mvpt render-zoo` (mv_post_train). Do not edit by hand.\n"
CAPTION_FULL = (
    r"Phase~1 (Tulu3 SFT and DPO) for all models at the 1.7B scale, both context variants "
    r"where both were evaluated. This is the complete version of "
    r"Table~\ref{tab:phase1_zoo}. " + wt.PROTOCOL_A_NOTE)

FAMILY_KEY = {"MV": "mv", "Nemotron": "nemotron", "FineWeb-Edu": "fineweb", "DCLM": "dclm",
              "Comma0.1": "comma", "SmolLM2": "smollm2", "Qwen2.5": "qwen25", "Qwen3": "qwen3"}
CONTEXT_KEY = {4096: "4k", 16384: "16k"}

#: Table 1's two blocks, as (title, [(family, name)]), the permissive mixtures first.
TABLE1_BLOCKS = (
    ("Matched compute, 300B tokens",
     [("MV", "MixtureVitae"), ("Comma0.1", "Comma0.1"), ("Nemotron", "Nemotron-CC-HQ"),
      ("FineWeb-Edu", "FineWeb-Edu"), ("DCLM", "DCLM")]),
    ("External references, 11--36T tokens, uncontrolled",
     [("SmolLM2", "SmolLM2 1.7B"), ("Qwen2.5", "Qwen2.5 1.5B"), ("Qwen3", "Qwen3 1.7B")]))
#: Table 1's column groups, by the domain of fs.DOMAIN.
TABLE1_DOMAINS = {"math": "Mathematics", "code": "Code", "science": "Science/QA",
                  "instruction": "IF"}
#: The matched-compute mixtures without front-loading, which the abstract compares with MV.
ORIGINAL_REFERENCES = ("Comma0.1", "Nemotron", "FineWeb-Edu", "DCLM")


def table1_context(values: dict[str, str], family: str) -> str:
    """The context key Table 1 shows for a family: 16K where it was evaluated."""
    return "16k" if f"{FAMILY_KEY[family]}.16k.dpo.avg" in values else "4k"


def check_claims(values: dict[str, str]) -> None:
    """Stop if a claim the abstract makes in words no longer holds for Table 1:
    after Tulu3 SFT and DPO, MixtureVitae's 16K model scores more than twice every
    original reference mixture and comes within five points of Qwen3-1.7B."""
    def dpo(family: str) -> float:
        return float(values[f"{FAMILY_KEY[family]}.{table1_context(values, family)}.dpo.avg"])
    mv = dpo("MV")
    top = max(ORIGINAL_REFERENCES, key=dpo)
    if not mv > 2 * dpo(top):
        raise ValueError(f"The abstract says that MixtureVitae after DPO ({mv}) scores more than "
                         f"twice the original reference mixtures, but {top} scores {dpo(top)}.")
    if not dpo("Qwen3") - mv < 5:
        raise ValueError(f"The abstract says that MixtureVitae after DPO ({mv}) comes within five "
                         f"points of Qwen3-1.7B, which scores {dpo('Qwen3')}.")


def phase1_table(summ: pd.DataFrame, out_dir: Path) -> Path:
    """Table 1: the Tulu3 SFT and DPO endpoint of each model on every task, then
    its suite average before Tulu3 and after each stage."""
    tasks = list(wt.BENCHMARKS)
    have = set(zip(summ.model_group, summ.context_length))
    value = {(r.model_group, r.context_length, r.stage, r.benchmark): (r.mean, r.sd)
             for r in summ.itertuples()}

    def context(family: str) -> int:
        return 16384 if (family, 16384) in have else 4096

    (_, matched), (_, external) = TABLE1_BLOCKS
    if any(context(f) != 16384 for f, _ in matched):
        raise ValueError("Table 1's caption says that every matched-compute model is at 16K.")
    extended = [name.split()[0] for f, name in external if context(f) == 16384]
    released = [name.split()[0] for f, name in external if context(f) != 16384]
    families = [f for _, rows in TABLE1_BLOCKS for f, _ in rows]
    sd = max(value[(f, context(f), s, "__suite__")][1] for f in families
             for s in ("base", "sft", "dpo"))
    caption = (
        r"\textbf{Phase~1 results for all models.} Benchmark columns are the endpoint after Tulu3 "
        r"SFT$\to$DPO, and the last three columns give the eleven-task suite average before "
        r"Tulu3 and after each stage. MixtureVitae and Comma0.1 are permissive. Matched-compute "
        r"models" + "".join(f" and {n}" for n in extended) + " are at 16K context, "
        + " and ".join(released) + " at their released context. "
        r"Protocol~A (Appendix Table~\ref{tab:eval-settings-A} defines the abbreviations), means "
        f"over three decoding seeds, with suite-average SD $\\le$ {math.ceil(sd * 10) / 10:.1f}. "
        r"Appendix Table~\ref{tab:phase1_zoo_full} gives SDs and both context lengths.")

    spans: list[list] = []          # [domain, first column, last column], counting Model as 1
    for i, t in enumerate(tasks, start=2):
        if spans and spans[-1][0] == fs.DOMAIN[t]:
            spans[-1][2] = i
        else:
            spans.append([fs.DOMAIN[t], i, i])
    width = len(tasks) + 4
    groups = " & ".join(f"\\multicolumn{{{b - a + 1}}}{{c}}{{{TABLE1_DOMAINS[d]}}}"
                        if b > a else TABLE1_DOMAINS[d] for d, a, b in spans)
    rules = ("".join(f"\\cmidrule(lr){{{a}-{b}}}" for _, a, b in spans)
             + f"\\cmidrule(l){{{width - 2}-{width}}}")
    lines = [r"\begin{table}[t]", f"\\caption{{{caption}}}", r"\label{tab:phase1_zoo}",
             r"\centering", r"\footnotesize", r"\setlength{\tabcolsep}{2pt}",
             f"\\begin{{tabular*}}{{\\linewidth}}{{@{{\\extracolsep{{\\fill}}}}l*{{{width - 1}}}{{c}}@{{}}}}",
             r"\toprule",
             f" & {groups} & \\multicolumn{{3}}{{c}}{{Suite average}} \\\\", rules,
             "Model & " + " & ".join(wt.BENCH_ABBR[t] for t in tasks) + r" & Base & SFT & DPO \\",
             r"\midrule"]
    for k, (title, rows) in enumerate(TABLE1_BLOCKS):
        if k:
            lines.append(r"\addlinespace")
        lines.append(f"\\multicolumn{{{width}}}{{@{{}}l}}{{\\textit{{{title}}}}} \\\\")
        for family, name in rows:
            ctx = context(family)
            cells = [f"{value[(family, ctx, 'dpo', t)][0]:.1f}" for t in tasks]
            cells += [f"{value[(family, ctx, s, '__suite__')][0]:.1f}" for s in ("base", "sft", "dpo")]
            lines.append(f"{name} & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular*}", r"\end{table}", ""]
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / "phase1_zoo.tex"
    path.write_text(HEADER + "\n".join(lines))
    return path


def summary(manifest_path: Path) -> pd.DataFrame:
    m = Manifest.load(manifest_path)
    scores = m.seed_scores(m.design("phase1_zoo")["cells"], pa.ZOO_KEYS)
    scores["domain"] = scores["benchmark"].map(fs.DOMAIN)
    return fs.benchmark_summary(scores, pa.ZOO_KEYS)


def macros(summ: pd.DataFrame) -> dict[str, str]:
    """Every printed cell of Table 6, as printed (one decimal, SD with two)."""
    out = {}
    task_key = {b: wt.BENCH_ABBR[b].lower() for b in wt.BENCHMARKS} | {"__suite__": "avg"}
    for r in summ.sort_values(pa.ZOO_KEYS + ["benchmark"]).itertuples():
        key = (f"{FAMILY_KEY[r.model_group]}.{CONTEXT_KEY[r.context_length]}.{r.stage}."
               f"{task_key[r.benchmark]}")
        out[key] = f"{r.mean:.1f}"
        out[key + ".sd"] = f"{r.sd:.2f}"
    return out


def write_macros(values: dict[str, str], path: Path) -> Path:
    lines = [
        HEADER.rstrip("\n"),
        "% Numbers for the text, from the same values as Tables 1 and 6.",
        r"% Use \pzoo{<key>}, for example \pzoo{mv.16k.base.avg} or \pzoo{qwen3.16k.dpo.avg}.",
        "% A key that does not exist prints in bold between question marks.",
    ] + macro_lines("pzoo", values)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")
    return path


def render_all(manifest_path: Path, out_dir: Path) -> list[Path]:
    summ = summary(manifest_path)
    values = macros(summ)
    check_claims(values)
    tables_dir = out_dir / "tables"
    tables = [phase1_table(summ, tables_dir),
              wt.zoo_perbenchmark(summ, tables_dir, headline_only=False, caption=CAPTION_FULL,
                                  header=HEADER, panels=wt.DOMAIN_PANELS)]
    return tables + [write_macros(values, tables_dir / "zoo_numbers.tex")]


def main(manifest_path: Path, out_dir: Path) -> int:
    written = render_all(manifest_path, out_dir)
    tables = [p for p in written if p.name != "zoo_numbers.tex"]
    pdf = preview.build("Tables 1 and 6, Phase 1 results for all models (render-zoo)", tables, [],
                        out_dir / "preview.pdf")
    for path in written + ([pdf] if pdf else []):
        print(f"  wrote {path}")
    return 0
