def _one(x: float) -> str:
    """A difference with one decimal, rounded once, with no negative zero."""
    return f"{round(x, 1) + 0.0:.1f}"


def _span(out: dict[str, str], key: str, values: list[str]) -> None:
    """min, max and range of printed values, each end as it is printed, and a
    negative one in math mode so that it prints a minus sign."""
    lo, hi = min(values, key=float), max(values, key=float)
    show = lambda v: f"\\ensuremath{{{v}}}" if v.startswith("-") else v  # noqa: E731
    out[f"{key}.min"], out[f"{key}.max"] = show(lo), show(hi)
    out[f"{key}.range"] = show(lo) if float(lo) == float(hi) else f"{show(lo)} to {show(hi)}"


def macros(groups_by_table: dict[str, list[list[Printed]]]) -> dict[str, str]:
    """Key -> printed text, for `\\plang{<key>}`. Tables are `abl`, `main`,
    `decon`, `small`, `phase2` and `mask`. Tasks are the column names in lower
    case (`arc-c`, `boolq`, `hellas`, ...), and `avg`.
      <table>.<row>.<task>                  one cell, for example main.mv.sft.avg
      <table>.<group>[.post].<task>.<min|max|range>
                                            over a group's rows, or its SFT and DPO rows
      <table>.<family>.<task>.<min|max|range>
                                            over the groups of FAMILIES, for example main.mv.all
      <table>.<gap>.<task>.<min|max|range>  over the row-by-row differences of GAPS
      <key>.<task>.<min|max|range>          over the differences of CROSS
    Ranges are taken from the printed values, so they read as the table does,
    each end as the table prints it. Differences are computed from the unrounded
    values and rounded once. A range prints "a to b",
    or one value when a equals b."""
    out = {}
    raw: dict[str, float] = {}
    columns = [c.lower() for c in COLUMNS]
    stages_of: dict[str, list[str]] = {}
    for table in TABLES:
        cells: dict[str, dict[str, list[tuple[str, str]]]] = {}
        exact: dict[str, dict[str, tuple[float, ...]]] = {}
        for spec, rows in zip(table.groups, groups_by_table[table.key]):
            for p in rows:
                if p.cells is None:
                    continue
                for c, v, x in zip(columns, p.cells, p.values):
                    out[f"{table.key}.{p.row.key}.{c}"] = v
                    raw[f"{table.key}.{p.row.key}.{c}"] = x
                group, stage = p.row.key.rsplit(".", 1)
                cells.setdefault(group, {}).setdefault(stage, list(zip(columns, p.cells)))
                exact.setdefault(group, {}).setdefault(stage, p.values)
        for group, stages in cells.items():
            stages_of[f"{table.key}.{group}"] = list(stages)
            for c_i, c in enumerate(columns):
                vals = [stages[st][c_i][1] for st in stages]
                post = [stages[st][c_i][1] for st in stages if st != "base"]
                _span(out, f"{table.key}.{group}.{c}", vals)
                if post and len(post) < len(vals):
                    _span(out, f"{table.key}.{group}.post.{c}", post)
        for fam, members in FAMILIES.get(table.key, {}).items():
            for c_i, c in enumerate(columns):
                vals = [cells[g][st][c_i][1] for g in members for st in cells[g]]
                _span(out, f"{table.key}.{fam}.{c}", vals)
        for gap, pairs in GAPS.get(table.key, {}).items():
            for c_i, c in enumerate(columns):
                diffs = [exact[a][st][c_i] - exact[b][st][c_i]
                         for a, b in pairs for st in exact[a] if st in exact[b]]
                _span(out, f"{table.key}.{gap}.{c}", [_one(d) for d in diffs])
    for key, (row, group) in CROSS.items():
        for c in columns:
            diffs = [raw[f"{row}.{c}"] - raw[f"{group}.{st}.{c}"] for st in stages_of[group]]
            _span(out, f"{key}.{c}", [_one(d) for d in diffs])
    return out


