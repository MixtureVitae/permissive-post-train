@dataclass(frozen=True)
class Printed:
    row: Row
    cells: list[str] | None     # COLUMNS, as printed; None for a label row
    values: tuple[float, ...] | None = None    # the same, unrounded


def printed_rows(table: Table, runs: dict[str, lr.Run]) -> list[list[Printed]]:
    out = []
    for group in table.groups:
        rows = []
        for row in group.rows:
            if row.source is None:
                rows.append(Printed(row, None))
            else:
                scores = runs[row.source].scores
                vals = [scores[t] for t in TASKS]
                vals = vals + [sum(vals) / len(vals)]
                rows.append(Printed(row, [f"{v:.1f}" for v in vals], tuple(vals)))
        out.append(rows)
    return out


def _bold_max(groups: list[list[Printed]]) -> list[float]:
    cols = [[float(p.cells[i]) for g in groups for p in g if p.cells] for i in range(len(COLUMNS))]
    return [max(c) for c in cols]


def table_tex(table: Table, groups: list[list[Printed]]) -> str:
    top = _bold_max(groups) if table.bold else None
    sections = any(g.section for g in table.groups)
    lead = [table.section_head] if sections else []
    head = " & ".join(lead + [r"\textbf{Model}"] + [f"\\textbf{{{c}}}" for c in COLUMNS]) + r" \\"
    ncols = len(COLUMNS) + (2 if sections else 1)
    lines = [r"\begin{table}[htbp]", r"\centering", f"\\caption{{{table.caption}}}",
             f"\\label{{{table.label}}}", r"\scriptsize", r"\setlength{\tabcolsep}{2pt}",
             f"\\begin{{tabular}}{{{'ll' if sections else 'l'}{'r' * len(COLUMNS)}}}", r"\toprule",
             head, r"\midrule"]
    for i, (spec, rows) in enumerate(zip(table.groups, groups)):
        if i and spec.section and table.rotate:
            lines.append(r"\midrule")
        elif i and sections and not spec.section:
            lines.append(f"\\cmidrule{{2-{ncols}}}")
        elif i:
            lines += [r"\midrule", r"\addlinespace[0.3em]"]
        first = ""
        if spec.section:
            n = sum(len(g.rows) for g in table.groups[i:i + 2])
            if table.rotate:
                lines.append(f"\\multirow{{{n}}}{{*}}{{{rotated(spec.section)}}}")
            else:
                first = f"\\multirow{{{n}}}{{*}}{{{spec.section}}}"
        for k, p in enumerate(rows):
            label = p.row.label
            if p.cells is None:
                cells = [""] * len(COLUMNS)
            else:
                cells = [f"\\textbf{{{c}}}" if top and float(c) == top[j] else c
                         for j, c in enumerate(p.cells)]
            pre = [first if k == 0 else ""] if sections else []
            lines.append(" & ".join(pre + [label] + cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    return "\n".join(lines) + "\n"


