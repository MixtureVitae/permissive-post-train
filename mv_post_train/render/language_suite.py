@dataclass(frozen=True)
class Row:
    label: str            # as printed
    key: str              # macro key below the table's
    source: str | None    # "<input>:<run>" (language_records), or None for a label row


@dataclass(frozen=True)
class Group:
    rows: tuple[Row, ...]
    section: str | None = None   # the section a group opens (Tables 12 and 16)


@dataclass(frozen=True)
class Table:
    name: str
    item: str
    key: str
    label: str
    caption: str
