@dataclass(frozen=True)
class Checkpoint:
    key: str                  # <model>.<stage>, the macro prefix
    label: str
    zip: str
    folders: tuple[str, ...]  # one per seed, in ls.SEEDS (R23: ls.R23_SEEDS) order

    @property
    def default(self) -> str:
        return self.folders[0]

    @property
    def run(self) -> str:
        """The `default` run, as language_records names it."""
        if self.zip == R23:
            return "R23:" + self.default.removesuffix("-seed1234").replace("__", "/", 1)
        return ("R8-fineweb:" if self.zip == FINEWEB else "R8:") + self.default.removesuffix("-default")


def _ck(key: str, label: str, stem: str, zip_name: str = R8,
        seeded_stem: str | None = None) -> Checkpoint:
    other = seeded_stem or stem
    return Checkpoint(key, label, zip_name,
                      tuple(f"{stem if s == 'default' else other}-{s}" for s in ls.SEEDS))


