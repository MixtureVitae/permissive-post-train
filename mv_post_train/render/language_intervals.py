"""Language-suite changes with paired question-level intervals.

The paper's language tables print one score per checkpoint, with no interval.
For the checkpoints whose per-question logs exist (R8: `language_eval-logs.zip`
and `logs-fineweb.zip`), this renders each training step's change on the
11-task language average and on every task, with a 95% interval and a
corrected q-value (`stats/language_changes.py`).

Each change is a checkpoint minus the checkpoint it was trained from. CHANGES
below lists which changes the tables print, and every one is checked against
the results manifest: its parents come from the model cards and training
summaries of the Hugging Face snapshot and, where those are silent, from the
checkpoint names (`manifest/lineage.py`). A multi-step change, from a 16K base
to a checkpoint several steps later, is labelled as one. So no change starts
from R8's 16K Nemotron-CC-HQ base except the context extension itself: the 16K
SFT model was trained from a different 16K model. The per-question scores must also give the manifest's score of every
task.

It also renders the front-loading study's language contrasts (Table 28), as
Table 27 gives them for reasoning: on the 11-task average of the sixteen
language cells of Table 31, the front-loading effect within each web dataset,
each permissive minus each non-permissive dataset, both front-loaded, and the
interaction. Seven cells are R8 checkpoints of MODELS. The other nine are
Harsh Raj's runs of 2026-10-26 (R23), the runs the manifest prints for them
(manifest/suites.R23_CELLS).

Values use the `default` prompt-example seed, the one the paper's tables use:
1234, for R8 and R23 alike. The same changes with each question averaged over
the three seeds are written next to them as a check. R23's other two seeds
(42 and 2025) are not R8's (1765181304 and 1819856179), so a three-seed
contrast between an R8 cell and an R23 cell averages different seeds.
"""
