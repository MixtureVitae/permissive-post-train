def manifest_keys(m: Manifest) -> dict[str, str]:
    """Checkpoint here -> its key in the results manifest, through the
    manifest's result for the checkpoint's `default` run."""
    from ..manifest.suites import LANGUAGE, interval_sources
    by_run = {f"{r['source']['input']}:{r['source']['run']}": r["checkpoint"]
              for r in m.data["results"] if r["protocol"] == LANGUAGE and "run" in r["source"]}
    return {key: by_run[src] for key, src in interval_sources().items()}


def check(change: Change, m: Manifest, keys: dict[str, str]) -> None:
    """Refuse a change that does not follow the manifest's lineage. A single
    step needs the parent the child was trained from, a multi-step change an
    earlier model of the child's line. Two names with the same weights are the
    same model. So R8's 16K Nemotron-CC-HQ base (…4096-long_sft_16k) is no
    parent of the 16K SFT model, which was trained from
    …16384-rope_theta-1M-long_sft_16k."""
    child, parent = keys[change.child], keys[change.parent]
    line = m.line(child)
    at = [i for i, k in enumerate(line) if m.same_model(k, parent)]
    ok = at and (at[0] >= 1 if change.multi_step else at[0] == 0)
    if not ok:
        raise ValueError(f"{change.child} from {change.parent} is refused: the manifest's line of "
                         f"{child} is {line or 'empty'}, and {parent} is "
                         + ("not in it." if not at else f"step {at[0] + 1} of it."))


def check_levels(items: pd.DataFrame, m: Manifest) -> None:
    """Stop unless every checkpoint's `default` run gives, on every task, the
    score the manifest holds for it."""
    from ..manifest.suites import LANGUAGE
    keys = manifest_keys(m)
    means = items.groupby(["folder", "task"])["score"].mean() * 100.0
    for c in CHECKPOINTS.values():
        for task in LANGUAGE_SUITE_TASKS:
            want = m.value(keys[c.key], task, LANGUAGE)
            if abs(float(means.loc[(c.default, task)]) - want) > 1e-9:
                raise ValueError(f"{c.key} {task}: the per-question scores give "
                                 f"{float(means.loc[(c.default, task)])}, the manifest {want}")


def folders_by_zip() -> dict[str, list[str]]:
    out: dict[str, list[str]] = {}
    for c in CHECKPOINTS.values():
        out.setdefault(c.zip, []).extend(c.folders)
    return out


def compute(items: pd.DataFrame, m: Manifest, *,
            n_boot: int = lc.N_BOOT) -> tuple[pd.DataFrame, pd.DataFrame]:
    """(levels, changes). Levels: percent per checkpoint and task (`avg` for the
    11-task average), for the `default` seed and the three-seed mean. Changes:
    one row per change, task and seed mode, with its interval and q-value."""
    lc.check_same_questions(items)
    for c in CHECKPOINTS.values():
        sessions = ([[f for f in c.folders for seed in group if f.endswith(f"-seed{seed}")]
                     for group in ls.R23_SESSIONS] if c.zip == R23 else None)
        lc.check_seed_invariant_tasks(items, list(c.folders), c.key, sessions)
    levels, rows = [], []
    keys = manifest_keys(m)
    for model, (_, cks) in MODELS.items():
        changes = CHANGES[model]
        for change in changes:
            check(change, m, keys)
        for mode, use in (("default", lambda c: [c.default]), ("three-seed mean", lambda c: list(c.folders))):
            scores = {c.key: lc.question_scores(items, use(c)) for c in cks}
            matrix = lc.Matrix.build(scores)
            means = matrix.task_means()
            for j, key in enumerate(matrix.columns):
                for t, task in enumerate(LANGUAGE_SUITE_TASKS):
                    levels.append(dict(checkpoint=key, mode=mode, task=task, value=means[t, j]))
                levels.append(dict(checkpoint=key, mode=mode, task=lc.AVG,
                                   value=means[:, j].mean()))
            out = lc.changes(matrix, [(c.child, c.parent) for c in changes], n_boot=n_boot)
            info = {(c.child, c.parent): c for c in changes}
            out["step"] = [info[(a, b)].step for a, b in zip(out["child"], out["parent"])]
            out["multi_step"] = [info[(a, b)].multi_step for a, b in zip(out["child"], out["parent"])]
            out.insert(0, "mode", mode)
            out.insert(0, "model", model)
            rows.append(out)
    return pd.DataFrame(levels), pd.concat(rows, ignore_index=True)


