def average_table(levels: pd.DataFrame, changes: pd.DataFrame) -> list[str]:
    avg = changes[changes["task"] == lc.AVG]
    lines = [r"\begin{table}[t]", r"\centering",
             r"\caption{Changes in the 11-task language average at each training step, with "
             r"95\% intervals. " + NOTE + "}", r"\label{tab:language_changes}", r"\scriptsize",
             r"\setlength{\tabcolsep}{3pt}", r"\begin{tabular}{llrrlrl}", r"\toprule",
             r"\textbf{Model} & \textbf{Change} & \textbf{From} & \textbf{To} & "
             r"\textbf{Change [95\% CI]} & \textbf{q} & \textbf{Three seeds} \\", r"\midrule"]
    for model, (name, _) in MODELS.items():
        rows = avg[(avg["model"] == model) & (avg["mode"] == "default")]
        three = avg[(avg["model"] == model) & (avg["mode"] == "three-seed mean")]
        for k, (_, c) in enumerate(rows.iterrows()):
            t = three[(three["child"] == c["child"]) & (three["parent"] == c["parent"])].iloc[0]
            d = printed_change(levels, c["child"], c["parent"], lc.AVG)
            d3 = printed_change(levels, c["child"], c["parent"], lc.AVG, "three-seed mean")
            lines.append(
                f"{name if k == 0 else ''} & {_change_label(c)} & "
                f"{_level(levels, c['parent'], lc.AVG):.2f} & "
                f"{_level(levels, c['child'], lc.AVG):.2f} & "
                f"{_signed(d, 2)} [{_signed(c['lo'], 2)}, {_signed(c['hi'], 2)}] & {_q(c['q'])} & "
                f"{_signed(d3, 2)} [{_signed(t['lo'], 2)}, {_signed(t['hi'], 2)}] \\\\")
        if model != list(MODELS)[-1]:
            lines.append(r"\midrule")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    return lines


def task_table(levels: pd.DataFrame, changes: pd.DataFrame, model: str = "mv") -> list[str]:
    name = MODELS[model][0]
    sel = changes[(changes["model"] == model) & (changes["mode"] == "default")]
