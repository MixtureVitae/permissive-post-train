def decimals(task: str) -> int:
    """The 11-task average moves by fractions of a point, so it is printed with
    two decimals. Single tasks keep one, like the paper's tables."""
    return 2 if task == lc.AVG else 1


def printed(x: float, nd: int = 1) -> float:
    """The value as printed with `nd` decimals (rounded once, no negative zero)."""
    return round(float(f"{x:.{nd}f}"), nd) + 0.0


def _signed(x: float, nd: int = 1) -> str:
    return f"{printed(x, nd):+.{nd}f}".replace("-", "$-$")


def _level(levels: pd.DataFrame, key: str, task: str, mode: str = "default") -> float:
    sel = levels[(levels["checkpoint"] == key) & (levels["task"] == task) & (levels["mode"] == mode)]
    return float(sel["value"].iloc[0])


def printed_change(levels: pd.DataFrame, child: str, parent: str, task: str,
                   mode: str = "default") -> float:
    """A change as printed: the difference of the two unrounded levels, rounded once."""
    nd = decimals(task)
    return printed(_level(levels, child, task, mode) - _level(levels, parent, task, mode), nd)


def _q(q: float) -> str:
    return "$<$0.001" if q < 0.001 else f"{q:.3f}"


def _write(out_dir: Path, name: str, lines: list[str]) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / name
    path.write_text(HEADER + "\n".join(lines) + "\n")
    return path


def _change_label(c: pd.Series) -> str:
    parent, child = CHECKPOINTS[c["parent"]], CHECKPOINTS[c["child"]]
    arrow = r" $\Rightarrow$ " if c["multi_step"] else r" $\to$ "
    return parent.label + arrow + child.label


