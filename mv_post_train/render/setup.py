def training_schedules(c: dict, checks: Checks, out: dict) -> str:
    rows = []
    for r in c["rows"]:
        cooldown = round(c["cooldown_fraction"] * r["iterations"])
        tokens = float(r["tokens"].rstrip("B")) * 1e9
        per_step = tokens / r["iterations"]
        stated = float(r["batch_tokens"].rstrip("M")) * 1e6
        sequences = per_step / c["sequence_length"]
        checks.add("Table 17", f"{r['tokens']}: tokens per iteration", r["batch_tokens"],
                   f"{per_step / 1e6:.3f}M ({sequences:.1f} sequences of {c['sequence_length']})",
                   abs(per_step - stated) < 0.01e6)
        key = f"schedule.{r['tokens'].lower()}"
        out |= {f"{key}.iterations": _thousands(r["iterations"]), f"{key}.warmup": _thousands(r["warmup"]),
                f"{key}.cooldown": _thousands(cooldown), f"{key}.batch": r["batch_tokens"]}
        rows.append(f"{r['tokens']:<5} & {r['batch_tokens']} & {_thousands(r['iterations']):<7} & "
                    f"${r['learning_rate']}$ & {_thousands(r['warmup']):<6} & {_thousands(cooldown):<6} \\\\")
    pct = f"{round(100 * c['cooldown_fraction'])}\\%"
    return "\n".join([
        r"\begin{table}[htbp]", r"\centering",
        r"\caption{The training schedules used in our experiments.}",
        f"\\label{{{c['label']}}}", r"\renewcommand{\arraystretch}{1.5}",
        r"\begin{tabular}{@{}l c c c c c@{}}", r"\toprule",
        r"\textbf{Tokens} &", r"\textbf{\makecell[c]{Global Batch Size \\ (tokens)}} &",
        r"\textbf{Iterations} &", r"\textbf{\makecell[c]{Learning \\ Rate}} &", r"\textbf{Warmup} &",
        f"\\textbf{{\\makecell[c]{{Cooldown \\\\ ({pct})}}}} \\\\", r"\midrule"] + rows + [
        r"\bottomrule", r"\end{tabular}", r"\end{table}"]) + "\n"


def architecture(c: dict, configs: dict[str, dict], out: dict) -> str:
    rows = []
    for r in c["rows"]:
        cfg = configs[r["config"]]
        non_emb, emb = parameters(cfg)
        total = non_emb + emb
        size = r["config"].split("-", 1)[1]
        out |= {f"arch.{size}.params": f"{total / 1e9:.2f}", f"arch.{size}.nonemb": f"{non_emb / 1e9:.2f}",
                f"arch.{size}.emb": f"{emb / 1e9:.2f}", f"arch.{size}.layers": str(cfg["num_hidden_layers"])}
        rows.append(f"${non_emb / 1e9:.2f} + {emb / 1e9:.2f} = {total / 1e9:.2f}$ & "
                    f"{cfg['num_hidden_layers']} & {cfg['hidden_size']} & {cfg['num_attention_heads']} & "
                    f"{cfg['intermediate_size']} & ${r['memory']}$ & ${_sci(6 * total)}$ \\\\")
    return "\n".join([
        r"\begin{table*}[htbp]", r"\centering",
        r"\caption{\textbf{open-sci-ref}~\citep{nezhurina2025opensciref} model architecture and "
        r"scales. We used tied embedding weights in all experiments.}",
        f"\\label{{{c['label']}}}", "", r"\renewcommand{\arraystretch}{1.5}",
        r"\begin{tabular}{@{}l c c c c c c@{}}", r"\toprule",
        r"\textbf{\makecell[l]{Parameters (B) \\ (Non-Emb + Emb)}} &", r"\textbf{Layers} &",
        r"\textbf{Hidden} &", r"\textbf{Heads} &", r"\textbf{\makecell[l]{FFN \\ Hidden}} &",
        r"\textbf{Memory} &", r"\textbf{\makecell[l]{FLOPs}} \\", r"\midrule"] + rows + [
        r"\bottomrule", r"\end{tabular}", r"\end{table*}"]) + "\n"


def sft_hyperparams(c: dict, out: dict) -> str:
    world = c["nodes"] * c["gpus_per_node"]
    values = dict(per_device_batch=c["per_device_batch"], gradient_accumulation=c["gradient_accumulation"],
                  world_size=world, nodes=c["nodes"], gpus_per_node=c["gpus_per_node"],
                  effective_batch=c["per_device_batch"] * c["gradient_accumulation"] * world)
    out |= {f"sft.{k.replace('_', '-')}": str(v) for k, v in values.items()}
    rows = []
    for name, value in c["rows"]:
        if not name:
            rows.append(value)
            continue
        for k, v in values.items():
            value = value.replace("{" + k + "}", str(v))
        rows.append(f"{name:<29} & {value} \\\\")
    return "\n".join([
        r"\begin{table}[htbp]", r"\centering",
        r"\caption{Hyperparameters used for OT3 (OpenThoughts-3, 30k samples) SFT runs.",
        r"All runs share the same recipe, and only the attention backend and chat template change "
        r"per architecture.}", f"\\label{{{c['label']}}}", r"\begin{tabular}{ll}", r"\toprule",
        r"Hyperparameter & Value \\", r"\midrule"] + rows + [
        r"\bottomrule", r"\end{tabular}", r"\end{table}"]) + "\n"


def _gpu_rows(rows) -> list[str]:
    return [f"{name:<32} & {attn:<4} & {hours:<3} & OT3 30K SFT \\\\" for name, attn, hours in rows]


def sft_gpu_hours(c: dict, out: dict) -> str:
    runs = [r for g in c["groups"] for r in g]
    total = sum(h for _, _, h in runs)
    gpus = c["nodes"] * c["gpus_per_node"]
    out |= {"gpu.ot30k.total": _thousands(total), "gpu.ot30k.runs": str(len(runs)),
            "gpu.ot30k.gpus": str(gpus)}
    body = []
    for i, g in enumerate(c["groups"]):
        if i:
            body.append(r"\addlinespace")
        body += _gpu_rows(g)
    return "\n".join([
        r"\begin{table}[htbp]", r"\centering", r"\caption{Single-run GPU-hours for OT3 (30k) SFT.",
        f"All runs: {gpus}~H100 ({c['nodes']} nodes $\\times$ {c['gpus_per_node']} GPUs). "
        r"Difference between groups",
        r"is the attention backend: FA2 (Llama/Qwen) is ${\sim}2\times$ faster than SDPA (opensci-arch).}",
        f"\\label{{{c['label']}}}", r"\begin{tabular}{llrl}", r"\toprule",
        r"Base model & Attention & GPU-hours & Training \\", r"\midrule"] + body + [
        r"\midrule", f"\\textbf{{Total ({len(runs)} runs)}}         &      & "
        f"\\textbf{{{total}}} & \\\\", r"\bottomrule", r"\end{tabular}", r"\end{table}"]) + "\n"


def long_ctx_gpu_hours(c: dict, out: dict) -> str:
    gpus = c["nodes"] * c["gpus_per_node"]
    out["gpu.longctx.gpus"] = str(gpus)
    out["gpu.longctx.total"] = str(sum(h for _, _, h in c["rows"]))
    # One row per distinct cost: the runs that cost the same are named together.
    groups: dict[tuple[str, int], list[str]] = {}
    for name, attn, hours in c["rows"]:
        groups.setdefault((attn, hours), []).append(name)
    def names(ns: list[str]) -> str:
        return ns[0] if len(ns) == 1 else ", ".join(ns[:-1]) + f" and {ns[-1]}, each"
    rows = [f"{names(ns)} & {attn} & {hours} & Long-ctx SFT (16k) \\\\"
            for (attn, hours), ns in groups.items()]
    return "\n".join([
        r"\begin{table}[htbp]", r"\centering",
        r"\caption{Single-run GPU-hours for long-context extension SFT.",
        f"All runs: {gpus}~GH200 ({c['nodes']} nodes $\\times$ {c['gpus_per_node']} GPUs), 1 epoch "
        r"($\approx$16k tokens/seq, YaRN RoPE scaling), SDPA attention.}  "
        f"\\label{{{c['label']}}}", r"\begin{tabular}{p{0.45\linewidth}lrl}", r"\toprule",
        r"Base model & Attention & GPU-hours & Training \\", r"\midrule"] + rows + [
        r"\bottomrule", r"\end{tabular}", r"\end{table}"]) + "\n"


def budget(c: dict, out: dict) -> str:
    names = [n for n, _ in c["columns"]]
    tokens = [t for _, t in c["columns"]]
    ref = tokens[0]
    for (name, t) in c["columns"][1:]:
        key = name.split("-")[0].lower().replace(".", "")
        out |= {f"budget.{key}.tokens": f"{t:g}", f"budget.{key}.ratio": f"{t / ref:.1f}",
                f"budget.{key}.ratio.whole": f"{round(t / ref)}"}
    out["budget.reference.tokens"] = f"{ref:g}"
    head = " & " + " & ".join(f"\\textbf{{{n.replace('{', chr(92) + '{').replace('}', chr(92) + '}')}}}"
                              for n in names) + r" \\"
    return "\n".join([
        r"\begin{table}[htbp]", r"\centering",
        r"\caption{Pretraining token budget for each model and its ratio relative to MV (300B "
        r"tokens). External open-weights references use substantially more pretraining compute than MV.}",
        f"\\label{{{c['label']}}}", r"\small", r"\begin{tabular}{l" + "r" * len(names) + "}",
        r"\toprule", head, r"\midrule",
        r"\# Tokens (T) & " + " & ".join(f"{t:g}" for t in tokens) + r" \\",
        r"Budget Ratio  & " + " & ".join(f"{t / ref:.1f}" for t in tokens) + r" \\",
        r"\bottomrule", r"\end{tabular}", r"\end{table}"]) + "\n"


def _protocol_head(domain: bool) -> list[str]:
    """Table 23's head has a Domain column after the task, Table 24's not."""
    return [r"\scriptsize", r"\setlength{\tabcolsep}{3pt}",
            r"\begin{tabularx}{\linewidth}{@{}l l " + ("l " if domain else "")
            + r"l >{\raggedright\arraybackslash}X c l r@{}}",
            r"\toprule",
            r"\textbf{Abbr.} & \textbf{Task} & " + (r"\textbf{Domain} & " if domain else "")
            + r"\textbf{Ref.} & \textbf{Metric} & \textbf{\#Shots} & "
            r"\textbf{Decoding} & \textbf{Max new toks} \\", r"\midrule"]


