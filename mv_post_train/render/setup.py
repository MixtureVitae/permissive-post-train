HEADER = "% Generated by `mvpt render-setup` (mv_post_train). Do not edit by hand.\n"
PREVIEW_PREAMBLE = "\\usepackage{makecell,tabularx}\\providecommand{\\citep}[1]{[#1]}\n"


def _thousands(n: int, brace: bool = False) -> str:
    return f"{n:,}".replace(",", "{,}" if brace else ",")


def _sci(x: float) -> str:
    """2.4\\times10^{9}: one decimal and a power of ten."""
    exp = len(str(int(x))) - 1
    mant = round(x / 10 ** exp, 1)
    if mant >= 10:
        mant, exp = mant / 10, exp + 1
    return f"{mant:.1f}\\times10^{{{exp}}}"


def parameters(config: dict) -> tuple[int, int]:
    """(non-embedding, embedding) parameters of an open-sci-ref model, from its
    config.json: attention with biases, a gated MLP with biases, two norms per
    layer, query and key norms, a final norm, and tied embeddings."""
    h, f, layers = config["hidden_size"], config["intermediate_size"], config["num_hidden_layers"]
    if config["num_key_value_heads"] != config["num_attention_heads"] or not config["tie_word_embeddings"]:
        raise ValueError("setup: parameters() counts tied embeddings and full key-value heads only")
    attention = 4 * (h * h + h)
    mlp = 3 * h * f + 2 * f + h
    norms = 2 * h + (2 * config["head_dim"] if config.get("qk_layernorm") else 0)
    return layers * (attention + mlp + norms) + h, config["vocab_size"] * h


class Checks:
    def __init__(self) -> None:
        self.rows: list[dict] = []

    def add(self, table: str, what: str, stated: str, computed: str, ok: bool) -> None:
        self.rows.append(dict(table=table, check=what, stated=stated, computed=computed,
                              result="ok" if ok else "differs"))
        if not ok:
            print(f"  Warning: {table}, {what}: stated {stated}, computed {computed}")

    def write(self, path: Path) -> Path:
        with open(path, "w", newline="") as f:
            w = csv.DictWriter(f, fieldnames=["table", "check", "stated", "computed", "result"],
                               lineterminator="\n")
            w.writeheader()
            w.writerows(self.rows)
        return path


