def _words(n: int) -> str:
    from .macros import number_word
    return number_word(n)


def domain_weights(out: dict) -> str:
    """Each domain's share of the suite average, into `out` as
    domain.<domain>.weight (percent), .n and .n.word, and as caption text."""
    counts = {d: sum(pa.DOMAIN[b] == d for b in pa.BENCHMARKS) for d in pa.DOMAINS}
    parts = []
    for d, n in counts.items():
        weight = f"{100 * n / len(pa.BENCHMARKS):.0f}"
        out |= {f"domain.{d}.weight": weight, f"domain.{d}.n": str(n),
                f"domain.{d}.n.word": _words(n)}
        parts.append(f"{DOMAIN_NAME[d].lower()} at {weight}\\%")
    return ", ".join(parts[:-1]) + f" and {parts[-1]}"


def protocol_a(c: dict, manifest: dict, out: dict) -> str:
    seeds = manifest["protocols"]["protocol_a"]["seeds"]
    seed_text = ", ".join(str(s) for s in seeds[:-1]) + f", and {seeds[-1]}"
    domain = {pa.BENCH_ABBR[b]: DOMAIN_NAME[pa.DOMAIN[b]] for b in pa.BENCHMARKS}
    if [a for a, *_ in c["tasks"]] != [pa.BENCH_ABBR[b] for b in pa.BENCHMARKS]:
        raise ValueError("Table 23's tasks are not the reasoning suite, in its order")
    rows = [f"{a:<5} & {task:<18} & {domain[a]} & \\citep{{{ref}}} & {metric} & {shots} & "
            f"{c['decoding']} & {_thousands(toks):>6} \\\\"
            for a, task, ref, metric, shots, toks in c["tasks"]]
    out |= {f"proto-a.{a.lower()}.max-tokens": _thousands(toks) for a, _, _, _, _, toks in c["tasks"]}
    out |= {f"proto-a.{a.lower()}.shots": str(shots) for a, _, _, _, shots, _ in c["tasks"]}
    out |= {f"proto-a.{a.lower()}.task": task for a, task, *_ in c["tasks"]}
    out |= {f"proto-a.{a.lower()}.metric": metric for a, _, _, metric, *_ in c["tasks"]}
    caption = CAPTION_A.replace("{seeds}", seed_text).replace("{weights}", domain_weights(out))
    return "\n".join([r"\begin{table}[htbp]", r"\centering", r"\caption{%", caption, "}",
                      f"\\label{{{c['label']}}}"]
                     + _protocol_head(True) + rows + [r"\bottomrule", r"\end{tabularx}", r"\end{table}"]) + "\n"


def protocol_b(c: dict, manifest: dict, limits: dict[str, int], runs: int, out: dict) -> str:
    proto = manifest["protocols"]["phase2_three_seed"]
    t = proto["temperature"]
    decoding = f"Sampling ($T{{=}}{t:g}$)"
    rows = []
    for a, task, ref, metric, shots, record_task in c["tasks"]:
        toks = limits[record_task]
        out[f"proto-b.{a.lower()}.max-tokens"] = _thousands(toks)
        out[f"proto-b.{a.lower()}.shots"] = str(shots)
        out[f"proto-b.{a.lower()}.task"] = task
        out[f"proto-b.{a.lower()}.metric"] = metric
        rows.append(f"{a:<5} & {task:<18} & \\citep{{{ref}}} & {metric} & {shots} & {decoding} & "
                    f"{_thousands(toks, brace=True)} \\\\")
    out["proto-b.temperature"] = f"{t:g}"
    return "\n".join([r"\begin{table}[htbp]", r"\centering", r"\caption{%",
                      CAPTION_B.replace("{t}", f"{t:g}").replace("{runs}", _words(runs)), "}", f"\\label{{{c['label']}}}"]
                     + _protocol_head(False) + rows + [r"\bottomrule", r"\end{tabularx}", r"\end{table}"]) + "\n"


METRIC_NAME = {"acc,none": "Accuracy", "acc_norm,none": "Normalized accuracy"}


def language_benchmarks(c: dict, settings: dict[str, tuple[int, str]], out: dict) -> str:
    rows = []
    for task, abbr, name, ref in c["tasks"]:
        shots, metric = settings[task]
        out[f"lang.{abbr.lower()}.shots"] = str(shots)
        rows.append(f"{abbr:<7} & {name:<13} & \\citep{{{ref}}} & {METRIC_NAME[metric]} & {shots} \\\\")
    return "\n".join([
        r"\begin{table}[htbp]", r"\centering", r"\caption{%",
        r"Standard language understanding evaluation benchmarks used in our result tables.",
        r"All tasks follow the default the LM Evaluation Harness~\citep{eval-harness} configurations,",
        r"with prompt-example seed 1234 and no chat template. Normalized accuracy is the harness's",
        r"\texttt{acc\_norm}, which scores each answer by its log-likelihood per byte. MMLU is the",
        r"harness's overall score, the mean over all 14{,}042 questions of its 57 subjects.%", "}",
        f"\\label{{{c['label']}}}", r"\scriptsize", r"\setlength{\tabcolsep}{3pt}",
        r"\begin{tabular}{@{}l l l l c@{}}", r"\toprule",
        r"\textbf{Abbr.} & \textbf{Task} & \textbf{Ref.} & \textbf{Metric} & \textbf{\#Shots} \\",
        r"\midrule"] + rows + [r"\bottomrule", r"\end{tabular}", r"\end{table}"]) + "\n"


