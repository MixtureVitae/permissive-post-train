def token_limits(meta_path: Path) -> tuple[dict[str, int], int]:
    """(task -> the one max_tokens value, the number of runs) of the three-seed
    Phase 2 records (decoding "sampling", as manifest/phase2.py selects them)."""
    import pandas as pd
    meta = pd.read_parquet(meta_path, columns=["task", "max_tokens", "decoding", "run_idx"])
    meta = meta[meta["decoding"] == "sampling"]
    limits = meta.groupby("task")["max_tokens"].unique()
    bad = {t: list(v) for t, v in limits.items() if len(v) != 1}
    if bad:
        raise ValueError(f"setup: Phase 2 tasks with several token limits: {bad}")
    return {t: int(v[0]) for t, v in limits.items()}, int(meta["run_idx"].nunique())


def render_all(manifest_path: Path, out_dir: Path) -> list[Path]:
    conf = tomllib.loads(inputs.path("C-setup").read_text())
    configs = {k: json.loads(inputs.path(k).read_text()) for k in ("S2-0.4b", "S2-1.7b")}
    manifest = json.loads(Path(manifest_path).read_text())
    limits, runs = token_limits(inputs.path("R14-meta"))
    settings = pa.language_settings(inputs.path("R13-language"))
    checks, out = Checks(), {}
    bodies = [training_schedules(conf["training_schedules"], checks, out),
              architecture(conf["architecture"], configs, out),
              sft_hyperparams(conf["ot30k_sft_hyperparams"], out),
              sft_gpu_hours(conf["ot30k_sft_gpu_hours"], out),
              long_ctx_gpu_hours(conf["long_ctx_gpu_hours"], out),
              budget(conf["budget"], out),
              protocol_a(conf["protocol_a"], manifest, out),
              protocol_b(conf["protocol_b"], manifest, limits, runs, out),
              language_benchmarks(conf["language_benchmarks"], settings, out)]
    a, b = out["proto-a.gsm8k.metric"], out["proto-b.gsm8k.metric"]
    checks.add("Tables 23 and 24", "GSM8K is scored the same way under both protocols", a, b, a == b)
    tables_dir = out_dir / "tables"
    tables_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for (name, _), body in zip(FILES, bodies):
        (tables_dir / name).write_text(HEADER + body)
        written.append(tables_dir / name)
    lines = [HEADER.rstrip("\n"), "% Numbers for the text, from the same values as Tables 17 to 25.",
             r"% Use \psetup{<key>}, for example \psetup{gpu.ot30k.total} or \psetup{budget.qwen3.ratio}.",
             "% A key that does not exist prints in bold between question marks."]
    (tables_dir / "setup_numbers.tex").write_text("\n".join(lines + macro_lines("psetup", out, sort=True)) + "\n")
    written.append(tables_dir / "setup_numbers.tex")
    written.append(checks.write(out_dir / "checks.csv"))
    return written


def main(manifest_path: Path, out_dir: Path) -> int:
    written = render_all(manifest_path, out_dir)
    tables = [p for p in written if p.suffix == ".tex" and p.name != "setup_numbers.tex"]
    pdf = preview.build("Tables 17 to 25, setup and evaluation settings (render-setup)", tables, [],
                        out_dir / "preview.pdf", PREVIEW_PREAMBLE)
    for path in written + ([pdf] if pdf else []):
        print(f"  wrote {path}")
    return 0
