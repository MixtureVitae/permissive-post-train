def factorial_summary(summary: pd.DataFrame, language_avg: pd.DataFrame, out_dir: Path, *,
                      pools: tuple[str, ...] = POOLS, permissive: tuple[str, ...] = PERMISSIVE,
                      note: str = "", pretraining: str = "pre-training",
                      pool_words: tuple[str, str] = WORKSHOP_POOL_WORDS,
                      exact_deltas: bool = False) -> Path:
    """Main table: suite averages of the factorial plus the language suite. The
    Delta row is the difference of the printed cells above it, or with
    `exact_deltas`, of the unrounded values, rounded once. A substrate
    with no language scores yet prints "--" there. `pretraining` is the
    caption's spelling: the workshop paper writes "pre-training", the main
    revision "pretraining"."""
    web = pool_words[0]
    look = _Summary(summary, FACTORIAL_KEYS)
    lang = language_avg.set_index(["model_group", "front_loading", "context_length"])["language"]
    lines = [
        r"\begin{table}[t]", r"\centering",
        r"\caption{\textbf{Front-loading versus source licensing at 300B " + pretraining +
        r" tokens.} Each \emph{no} and \emph{yes} row is one 1.7B model trained under the "
        r"identical \texttt{open-sci-ref} configuration, differing only in the " + web +
        r" and in whether the MixtureVitae instruction-and-reasoning subset is included. "
        r"Reasoning columns are the eleven-benchmark suite average under " + PROTOCOL_A_NOTE +
        r" Language columns are the eleven-task understanding suite on the corresponding "
        + _with_note(r"base checkpoint, single seed. $\Delta$ rows give the front-loading effect "
                   r"in percentage points.}", note),
        r"\label{tab:factorial}", r"\small", r"\setlength{\tabcolsep}{3.5pt}",
        r"\resizebox{\linewidth}{!}{%",
        r"\begin{tabular}{llrrrrrrrr}", r"\toprule",
        r"& & \multicolumn{3}{c}{\textbf{Reasoning, 4K}} & "
        r"\multicolumn{3}{c}{\textbf{Reasoning, 16K}} & "
        r"\multicolumn{2}{c}{\textbf{Language}} \\",
        r"\cmidrule(lr){3-5}\cmidrule(lr){6-8}\cmidrule(lr){9-10}",
        r"\textbf{" + web[0].upper() + web[1:] + r"} & \textbf{Front-loaded} & Base & SFT & DPO"
        r" & Base & SFT & DPO & 4K & 16K \\",
        r"\midrule",
    ]
    for i, pool in enumerate(pools):
        if i:
            lines.append(r"\addlinespace[0.35em]")
        label = POOL_LABEL[pool] + (r" \emph{(permissive)}" if pool in permissive else "")
        printed: dict[bool, list[tuple[float | None, float | None]]] = {}
        exact: dict[bool, list[float | None]] = {}
        for fl in (False, True):
            cells: list[tuple[float, float | None]] = []
            values: list[float | None] = []
            for ctx in (4096, 16384):
                for stage in STAGES:
                    m, s = look(pool, fl, ctx, stage, benchmark="__suite__")
                    cells.append((round(m, 1), s))
                    values.append(m)
            for ctx in (4096, 16384):
                v = float(lang.loc[(pool, fl, ctx)]) if (pool, fl, ctx) in lang.index else None
                cells.append((None if v is None else round(v, 1), None))
                values.append(v)
            printed[fl], exact[fl] = cells, values
        for k, (fl, name) in enumerate(((False, "no"), (True, "yes"))):
            body = " & ".join("--" if m is None else _ms(m, s) if s is not None else f"{m:.1f}"
                              for m, s in printed[fl])
            first = r"\multirow{3}{*}{" + label + "}" if k == 0 else ""
            lines.append(f"{first} & {name} & {body} \\\\")
        pairs = (zip(exact[False], exact[True]) if exact_deltas else
                 ((no[0], yes[0]) for no, yes in zip(printed[False], printed[True])))
        delta = " & ".join("--" if no is None or yes is None else f"${round(yes - no, 1) + 0.0:+.1f}$"
                           for no, yes in pairs)
        lines.append(f" & $\\Delta$ & {delta} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}}", r"\end{table}", ""]
    return _write(out_dir, "factorial_summary.tex", lines)


#: Column panels for the paper's per-benchmark tables: (title, tasks), with
#: "__suite__" for the suite average. Each panel is a float of its own, and the
#: later ones continue the first (\ContinuedFloat), so the table keeps one number.
DOMAIN_PANELS = (
    ("Mathematics", ("AIME24", "AIME25", "AMC23", "MATH500", "gsm8k")),
    ("Code, science and instruction following, and the suite average",
     ("HumanEval", "LiveCodeBench", "MBPP", "GPQADiamond", "JEEBench", "IFEval", "__suite__")),
)


def _panel_floats(look: _Summary, blocks: list, caption: str, label: str,
                  panels: tuple) -> list[str]:
    """The table as column panels (`panels`, as DOMAIN_PANELS), each in a float of
    its own at a readable size, the first with the caption and the label."""
    lines = []
    for k, (title, tasks) in enumerate(panels):
        cols = len(tasks) + 1
        letter = "abcdefgh"[k]
        cap = (caption + f" The table has {number_word(len(panels))} panels: "
               + ", ".join(f"({'abcdefgh'[i]}) {t.lower()}" for i, (t, _) in enumerate(panels))
               + "." if k == 0 else f"(continued) Panel ({letter}), {title.lower()}.")
        lines += [r"\begin{table}[t]", *([r"\ContinuedFloat"] if k else []), r"\centering",
                  f"\\caption{{{cap}}}", *([f"\\label{{{label}}}"] if k == 0 else []),
                  r"\footnotesize", r"\setlength{\tabcolsep}{4pt}",
                  r"\begin{tabular}{l" + "r" * len(tasks) + "}", r"\toprule",
                  f"\\multicolumn{{{cols}}}{{l}}{{\\textbf{{({letter}) {title}}}}} \\\\", r"\midrule",
                  r"\textbf{Model} & " + " & ".join(
                      r"\textbf{Avg}" if t == "__suite__" else f"\\textbf{{{BENCH_ABBR[t]}}}"
                      for t in tasks) + r" \\", r"\midrule"]
        for block in blocks:
            if isinstance(block, str):
                lines += [r"\addlinespace[0.15em]",
                          f"\\multicolumn{{{cols}}}{{l}}{{\\textit{{{block}}}}} \\\\"]
                continue
            group, rows = block
            lines.append(r"\addlinespace[0.2em]")
            for i, (row_label, key) in enumerate(rows):
                cells = [_ms(*look(*key, benchmark=t)) for t in tasks]
                lines.append(f"{group if i == 0 else ''}{row_label} & " + " & ".join(cells) + r" \\")
            lines.append(r"\midrule")
        lines[-1] = r"\bottomrule"
        lines += [r"\end{tabular}", r"\end{table}", ""]
    return lines


def _perbenchmark(look: _Summary, blocks: list, caption: str, label: str,
                  out_dir: Path, name: str, header: str = HEADER,
                  panels: tuple | None = None) -> Path:
    """`blocks` holds section titles (str) and (row-group label, [(row label, key)]).
    With `panels` (as DOMAIN_PANELS) the table is cut into column panels
    (_panel_floats). Without, it is the one wide table of the workshop paper."""
    if panels is not None:
        return _write(out_dir, name, _panel_floats(look, blocks, caption, label, panels), header)
    lines = [
        r"\begin{table}[t]", r"\centering", f"\\caption{{{caption}}}", f"\\label{{{label}}}",
        r"\scriptsize", r"\setlength{\tabcolsep}{3pt}",
        r"\resizebox{\linewidth}{!}{%",
        r"\begin{tabular}{l" + "r" * 12 + "}", r"\toprule",
        r"\textbf{Model} & " + " & ".join(f"\\textbf{{{BENCH_ABBR[b]}}}" for b in BENCHMARKS)
        + r" & \textbf{Avg} \\", r"\midrule",
    ]
    for block in blocks:
        if isinstance(block, str):
            lines += [r"\addlinespace[0.15em]", r"\multicolumn{13}{l}{\textit{" + block + r"}} \\"]
            continue
        group, rows = block
        lines.append(r"\addlinespace[0.2em]")
        for i, (row_label, key) in enumerate(rows):
            cells = [_ms(*look(*key, benchmark=b)) for b in BENCHMARKS]
            cells.append(_ms(*look(*key, benchmark="__suite__")))
            lines.append(f"{group if i == 0 else ''}{row_label} & " + " & ".join(cells) + r" \\")
        lines.append(r"\midrule")
    lines[-1] = r"\bottomrule"
    lines += [r"\end{tabular}}", r"\end{table}", ""]
    return _write(out_dir, name, lines, header)


def factorial_perbenchmark(summary: pd.DataFrame, out_dir: Path, *,
                           pools: tuple[str, ...] = POOLS, note: str = "",
                           pretraining: str = "pre-training",
                           pool_words: tuple[str, str] = WORKSHOP_POOL_WORDS,
                           panels: tuple | None = None) -> Path:
    blocks = []
    for ctx, tag in ((4096, ""), (16384, "-16K")):
        for pool in pools:
            for fl in (True, False):
                group = POOL_LABEL[pool].replace("Nemotron-CC-HQ", "Nemotron") + tag
                group += " (FL)" if fl else ""
                blocks.append((group, [(rl, (pool, fl, ctx, st)) for rl, st in STAGE_ROWS]))
    return _perbenchmark(
        _Summary(summary, FACTORIAL_KEYS), blocks,
        r"Per-benchmark results for the 300B front-loading $\times$ "
        + pool_words[0].replace(" ", "-") + r" factorial. "
        r"(FL) marks the models whose " + pretraining + r" mixture includes the MixtureVitae "
        r"instruction-and-reasoning subset. " + PROTOCOL_A_NOTE + (" " + note if note else ""),
        "tab:factorial_perbenchmark", out_dir, "factorial_perbenchmark.tex", panels=panels)


def zoo_perbenchmark(summary: pd.DataFrame, out_dir: Path, *, headline_only: bool,
                     caption: str | None = None, header: str = HEADER,
                     panels: tuple | None = None) -> Path:
    """Phase 1 for all models. `headline_only` keeps one context per family:
    16K where it exists, else the released context (main-text table).
    `caption` replaces the workshop paper's caption (render/zoo.py passes the
    main revision's)."""
    look = _Summary(summary, ["model_group", "context_length", "stage"])
    blocks: list = []
    for group in ZOO_ORDER:
        if group == ZOO_MATCHED[0]:
            blocks.append("Matched compute, 300B tokens, controlled comparison")
        if group == "SmolLM2":
            blocks.append("External open-weights references, 11--36T tokens, uncontrolled")
        contexts = sorted(summary.loc[summary["model_group"] == group, "context_length"].unique())
        for ctx in contexts[-1:] if headline_only else contexts:
            head = ZOO_LABEL[group] + ("-16K" if ctx == 16384 else "")
            blocks.append((head, [(rl, (group, ctx, st)) for rl, st in STAGE_ROWS]))
    if headline_only:
        default = (
            r"\textbf{Phase~1 across the model zoo.} One context variant per model family, "
            r"namely the 16K variant where one exists and the released context "
            r"otherwise. The matched-compute models are trained on 300B tokens under the "
            r"\texttt{open-sci-ref} protocol, while SmolLM2, Qwen2.5, and Qwen3 use 11T, 18T, and 36T "
            r"tokens respectively and are uncontrolled upper references. Both context variants of "
            r"every model are in Table~\ref{tab:phase1_zoo_full}. " + PROTOCOL_A_NOTE)
        label, name = "tab:phase1_zoo", "phase1_zoo.tex"
    else:
        default = (
            r"Phase~1 (Tulu3 SFT and DPO) across the model zoo at 1.7B scale, both context "
            r"variants. This is the complete version of Table~\ref{tab:phase1_zoo}. "
            + PROTOCOL_A_NOTE)
        label, name = "tab:phase1_zoo_full", "phase1_zoo_full.tex"
    return _perbenchmark(look, blocks, caption if caption is not None else default, label,
                         out_dir, name, header, panels)


def factorial_language(language: pd.DataFrame, out_dir: Path, *,
                       pools: tuple[str, ...] = POOLS, note: str = "",
                       pool_words: tuple[str, str] = WORKSHOP_POOL_WORDS,
                       checkpoint_words: str = "base and post-YaRN 16K checkpoints",
                       fit: bool = True) -> Path:
    """Substrates with no language scores yet are left out (say so in `note`).
    `checkpoint_words` names the checkpoints in the caption. Without `fit`, the
    table is not scaled to the line width but set with narrower columns."""
    wide = language.pivot_table(index=["model_group", "front_loading", "context_length"],
                                columns="task", values="performance")
    shown = [p for p in pools if p in set(language["model_group"])]
    n = number_word(4 * len(shown))
    lines = [
        r"\begin{table}[t]", r"\centering",
        f"\\caption{{Language understanding for the {n} factorial checkpoints, on the "
        + checkpoint_words + r". This suite is scored by the LM Evaluation "
        r"Harness under its own settings and is not on either reasoning protocol. "
        r"Single seed. Accuracies in percent, "
        r"\texttt{acc\_norm} where the harness reports it, and shot counts are in "
        r"Table~\ref{tab:eval_settings_general}. Without front-loading, FineWeb-Edu and the "
        + _with_note(r"MixtureVitae " + pool_words[1] + r" sit at chance on MMLU and "
                     r"CommonsenseQA.}", note),
        r"\label{tab:factorial_language}", r"\scriptsize",
        r"\setlength{\tabcolsep}{3pt}" if fit else r"\setlength{\tabcolsep}{2pt}",
        *([r"\resizebox{\linewidth}{!}{%"] if fit else []),
        r"\begin{tabular}{ll" + "r" * (len(LANGUAGE_TASKS) + 1) + "}", r"\toprule",
        r"\textbf{Model} & \textbf{FL} & "
        + " & ".join(f"\\textbf{{{LANGUAGE_ABBR[t]}}}" for t in LANGUAGE_TASKS)
        + r" & \textbf{Avg} \\", r"\midrule",
    ]
    for ctx, tag in ((4096, ""), (16384, "-16K")):
        for pool in shown:
            for fl in (True, False):
                vals = [float(wide.loc[(pool, fl, ctx), t]) for t in LANGUAGE_TASKS]
                name = POOL_LABEL[pool].replace("Nemotron-CC-HQ", "Nemotron") + tag
                lines.append(f"{name} & {'yes' if fl else 'no'} & "
                             + " & ".join(f"{v:.1f}" for v in vals)
                             + f" & {np.mean(vals):.1f}" + r" \\")
        lines.append(r"\midrule")
    lines[-1] = r"\bottomrule"
    lines += [r"\end{tabular}" + ("}" if fit else ""), r"\end{table}", ""]
    return _write(out_dir, "factorial_language.tex", lines)


def _contrast_titles(pool_words: tuple[str, str]) -> dict[str, str]:
    return {"front-loading": f"Front-loading effect, within {pool_words[0]}",
            "permissiveness": f"Permissive minus non-permissive {pool_words[1]}, both front-loaded",
            "interaction": "Interaction: front-loading effect, permissive minus non-permissive"}


def contrasts_table(contrasts: pd.DataFrame, out_dir: Path, *, note: str = "",
                    pools: tuple[str, ...] | None = None,
                    pool_words: tuple[str, str] = WORKSHOP_POOL_WORDS,
                    rounding_note: bool = True) -> Path:
    """With `pools`, the 4K and 16K contrasts sit side by side, in the order of
    `pools`, so a design with more substrates still fits on one page. Without
    `rounding_note`, the caption does not say that the estimates can differ
    from the difference of the rounded values, which the main revision's
    tables no longer print."""
    title = _contrast_titles(pool_words)
    lines = [
        r"\begin{table}[t]", r"\centering",
        r"\caption{All Protocol~A contrasts on the eleven-benchmark suite average, with "
        r"95\% paired item-level bootstrap intervals (2{,}000 replicates, items resampled "
        r"within benchmark, decoding seeds averaged first) and Benjamini--Hochberg adjusted "
        r"$q$-values computed within each family. Positive values favour front-loading in "
        r"the first block and the permissive " + pool_words[1] + r" in the second."
        + (r" Estimates are computed on unrounded item-level scores, so they can differ in the "
           r"final digit from the difference of the rounded values printed in "
           + _with_note(r"Table~\ref{tab:factorial}.}", note) if rounding_note
           else _with_note("}", note)),
        r"\label{tab:contrasts}", r"\small", r"\setlength{\tabcolsep}{5pt}",
    ]
    if pools is not None:
        return _write(out_dir, "contrasts.tex",
                      lines + _contrasts_side_by_side(contrasts, pools, title))
    lines += [
        r"\begin{tabular}{llrlr}", r"\toprule",
        r"\textbf{Contrast} & \textbf{Stage} & \textbf{Estimate} & \textbf{95\% CI} & "
        r"\textbf{$q$} \\", r"\midrule",
    ]
    for family in ("front-loading", "permissiveness", "interaction"):
        fam = contrasts[contrasts["family"] == family]
        for ctx in (4096, 16384):
            lines.append(r"\multicolumn{5}{l}{\emph{" + title[family]
                         + f", {'4K' if ctx == 4096 else '16K'} context" + r"}} \\")
            sub = fam[fam["context_length"] == ctx]
            for label in sorted(sub["label"].unique()):
                for stage in STAGES:
                    r = sub[(sub["label"] == label) & (sub["stage"] == stage)].iloc[0]
                    q = r"$<0.001$" if r.q < 0.001 else f"${r.q:.3f}$"
                    lines.append(f"\\quad {POOL_LABEL.get(label, label)} & {STAGE_HEAD[stage]} & "
                                 f"${r.estimate:+.2f}$ & $[{r.lo:+.2f}, {r.hi:+.2f}]$ & {q} \\\\")
            lines.append(r"\addlinespace[0.2em]")
        lines[-1] = r"\midrule"
    lines[-1] = r"\bottomrule"
    lines += [r"\end{tabular}", r"\end{table}", ""]
    return _write(out_dir, "contrasts.tex", lines)


def _contrast_label(label: str) -> str:
    if " - " not in label:
        return POOL_LABEL.get(label, label)
    a, b = label.split(" - ")
    return f"{SHORT.get(a, a)} $-$ {SHORT.get(b, b)}"


def _contrasts_side_by_side(contrasts: pd.DataFrame, pools: tuple[str, ...],
                            title: dict[str, str]) -> list[str]:
    rank = {p: i for i, p in enumerate(pools)}

    def order(label: str) -> tuple:
        return tuple(rank.get(part, len(rank)) for part in label.split(" - "))

    lines = [
        r"\resizebox{\linewidth}{!}{%", r"\begin{tabular}{llrlrrlr}", r"\toprule",
        r"& & \multicolumn{3}{c}{\textbf{4K context}} & "
        r"\multicolumn{3}{c}{\textbf{16K context}} \\",
        r"\cmidrule(lr){3-5}\cmidrule(lr){6-8}",
        r"\textbf{Contrast} & \textbf{Stage} & \textbf{Estimate} & \textbf{95\% CI} & "
        r"\textbf{$q$} & \textbf{Estimate} & \textbf{95\% CI} & \textbf{$q$} \\", r"\midrule",
    ]
    for family in ("front-loading", "permissiveness", "interaction"):
        fam = contrasts[contrasts["family"] == family]
        lines.append(r"\multicolumn{8}{l}{\emph{" + title[family] + r"}} \\")
        for label in sorted(fam["label"].unique(), key=order):
            for stage in STAGES:
                cells = []
                for ctx in (4096, 16384):
                    r = fam[(fam["label"] == label) & (fam["stage"] == stage)
                            & (fam["context_length"] == ctx)].iloc[0]
                    q = r"$<0.001$" if r.q < 0.001 else f"${r.q:.3f}$"
                    cells += [f"${r.estimate:+.2f}$", f"$[{r.lo:+.2f}, {r.hi:+.2f}]$", q]
                name = _contrast_label(label) if stage == STAGES[0] else ""
                lines.append(f"\\quad {name} & {STAGE_HEAD[stage]} & " + " & ".join(cells) + r" \\")
        lines.append(r"\midrule")
    lines[-1] = r"\bottomrule"
    return lines + [r"\end{tabular}}", r"\end{table}", ""]


def domain_robustness(scores: pd.DataFrame, out_dir: Path, *, pools: tuple[str, ...] = POOLS,
                      permissive: tuple[str, ...] = PERMISSIVE, note: str = "",
                      claim: str | None = None, protocol_note: str = PROTOCOL_A_NOTE,
                      fit: bool = True) -> Path:
    """Front-loading effect and substrate gap at 16K after SFT, under the plain
    suite average, the equal-domain average and each leave-one-domain-out view.
    `claim` replaces the workshop caption's sentence on what the views show, and
    `protocol_note` its note on the protocol and on what a cell holds. Without
    `fit`, a wide table is not scaled to the line width: it is set at
    footnote size, with each contrast's header on three lines."""
    if claim is None:
        claim = (r"neither the front-loading effect nor the substrate contrast depends on that "
                 r"weighting.")
    keys = FACTORIAL_KEYS
    pairs = [(a, b) for a in permissive for b in pools if b not in permissive]
    wide = fit and len(pools) + len(pairs) > 5   # the workshop's five columns fit as they are
    stacked = not fit and len(pools) + len(pairs) > 5
    loo = fs.leave_one_domain_out(scores, keys)
    views = [("Suite average (11 tasks)", fs.suite_average(scores, keys)),
             ("Equal-domain average", fs.equal_domain_average(scores, keys))]
    views += [(f"Drop {d} domain", loo[loo["dropped"] == d]) for d in DOMAINS]

    def level(frame: pd.DataFrame, pool: str, fl: bool) -> float:
        sel = frame[(frame["context_length"] == 16384) & (frame["stage"] == "sft")
                    & (frame["model_group"] == pool) & (frame["front_loading"] == fl)]
        return float(sel["mean"].iloc[0])

    lines = [
        r"\begin{table}[t]", r"\centering",
        r"\caption{Robustness of the two headline quantities to how the suite average is "
        r"weighted, at 16K context after Tulu3 SFT. The eleven-task macro average implicitly "
        r"weights math at 45\% and code at 27\%, and " + claim + " " + protocol_note
        + (" " + note if note else "") + r"}",
        r"\label{tab:domain_robustness}", r"\footnotesize" if stacked else r"\small",
        *([r"\setlength{\tabcolsep}{3pt}"] if stacked else []),
        *([r"\resizebox{\linewidth}{!}{%"] if wide else []),
        r"\begin{tabular}{l" + "r" * (len(pools) + len(pairs)) + "}", r"\toprule",
        f"& \\multicolumn{{{len(pools)}}}{{c}}{{\\textbf{{Front-loading effect}}}} & "
        f"\\multicolumn{{{len(pairs)}}}{{c}}{{\\textbf{{Permissive $-$ non-permissive}}}} \\\\",
        f"\\cmidrule(lr){{2-{1 + len(pools)}}}"
        f"\\cmidrule(lr){{{2 + len(pools)}-{1 + len(pools) + len(pairs)}}}",
        r"\textbf{Averaging view} & " + " & ".join([SHORT[p] for p in pools] + [
            (f"\\makecell{{{SHORT[a]}\\\\vs.\\\\{SHORT[b]}}}" if stacked else
             (r"vs.\ " if len(permissive) == 1 else SHORT[a] + r" vs.\ ") + SHORT[b])
            for a, b in pairs]) + r" \\",
        r"\midrule",
    ]
    for name, frame in views:
        effects = [level(frame, p, True) - level(frame, p, False) for p in pools]
        gaps = [level(frame, a, True) - level(frame, b, True) for a, b in pairs]
        lines.append(f"{name} & " + " & ".join(f"${v:+.1f}$" for v in effects + gaps) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}" + ("}" if wide else ""), r"\end{table}", ""]
    return _write(out_dir, "domain_robustness.tex", lines)


