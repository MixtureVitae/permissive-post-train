"""The workshop paper's eleven generated tables, rendered from this repo.

Seven tables are computed from the Protocol A per-sample records
(`data/protocol_a.py`, `stats/factorial.py`). Four are Protocol B tables whose
values are transcribed constants (`data/protocol_b.py`). Each function writes
one `.tex` whose basename, label and caption match the paper's file, so
`mvpt check-workshop` can compare the two cell by cell and a plain `diff`
shows any wording drift.

Rounding is single and explicit: means are printed to one decimal and SDs to
two, each rounded once from the unrounded value. A delta printed next to two
rounded cells is the difference of those printed cells, so it can be checked
by eye. Contrasts and the domain-robustness view are computed on unrounded
values.
"""
