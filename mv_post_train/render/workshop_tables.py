HEADER = "% Generated by `mvpt render-workshop` (mv_post_train). Do not edit by hand.\n"

PROTOCOL_A_NOTE = (
    "Protocol~A (Appendix Table~\\ref{tab:eval-settings-A}). "
    "Values are mean$_{\\pm\\text{SD}}$ over decoding seeds 42, 1234, and 2025."
)
PROTOCOL_B_NOTE = (
    "Protocol~B, the reasoning post-training protocol (Appendix Table~\\ref{tab:eval-settings-B}). "
    "Single seed, so no error bars are available."
)
STAGE_HEAD = {"base": "Base", "sft": "SFT", "dpo": "DPO"}
STAGE_ROWS = (("", "base"), (r"\quad $\to$ SFT", "sft"), (r"\quad $\to$ SFT $\to$ DPO", "dpo"))


def _write(out_dir: Path, name: str, lines: list[str], header: str = HEADER) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / name
    path.write_text(header + "\n".join(lines))
    return path


def _ms(mean: float, sd: float) -> str:
    return f"{mean:.1f}$_{{\\pm{sd:.2f}}}$"


def _with_note(caption_end: str, note: str) -> str:
    """Append `note` to a caption whose last line is `caption_end` (ending in "}")."""
    return caption_end[:-1] + " " + note + "}" if note else caption_end


SHORT = {"MV": "MV", "Nemotron": "Nemotron", "FineWeb-Edu": "FineWeb", "Comma": "Comma"}

# How the factorial's tables name its web-data factor: the full name, then the
# noun alone. The workshop paper writes "web substrate" and "substrate", the
# main revision passes ("source pool", "source pool").
WORKSHOP_POOL_WORDS = ("web substrate", "substrate")


class _Summary:
    """(mean, sd) lookup into a `benchmark_summary` frame."""

    def __init__(self, summary: pd.DataFrame, keys: list[str]):
        self._t = summary.set_index(keys + ["benchmark"])[["mean", "sd"]]

    def __call__(self, *key, benchmark: str) -> tuple[float, float]:
        row = self._t.loc[(*key, benchmark)]
        return float(row["mean"]), float(row["sd"])


