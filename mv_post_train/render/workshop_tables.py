def phase2_endpoints(out_dir: Path) -> Path:
    lines = _protocol_b_head(
        r"Reasoning post-training endpoints. Identical OpenThoughts3-30K "
        r"post-training (30K samples, 5 epochs) is applied to every model, starting from the "
        r"checkpoint named in each block's first row. Starting checkpoints are re-evaluated "
        r"here, so these values are paired within the table and must not be compared against "
        r"the Phase~1 tables. " + PROTOCOL_B_NOTE,
        "tab:phase2_endpoints", r"\scriptsize", "3pt", "Model") + [r"\midrule"]
    current = None
    for group, row_label, _, vals in pb.PHASE2_ENDPOINTS:
        if group != current:
            if current is not None:
                lines.append(r"\midrule")
            current = group
            name = f"{group} (base)" if row_label == "base" else f"{group} {row_label}"
        else:
            name = r"\quad " + row_label.replace(r"\quad ", "")
        lines.append(name + " & " + " & ".join(f"{v:.1f}" for v in vals) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}}", r"\end{table}", ""]
    return _write(out_dir, "phase2_endpoints.tex", lines)


